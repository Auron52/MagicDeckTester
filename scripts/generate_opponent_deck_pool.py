#!/usr/bin/env python3
"""Freeze 50 selected primary Cockatrice mainboards for passive opponents.

The repository also has alias directories and three text-only decks (Burn, Slivers,
Treasure Hunt). The selected 50 each have a primary 60-card .cod mainboard; their
explicit order fixes the seed % 50 mapping as more decks are added.

Run this after changing a selected decklist; --check detects stale generated data.
The C++ binary carries the pool so its result does not depend on the working directory.
"""

import argparse
import json
from pathlib import Path
import sys
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src/core/OpponentDeckPool.h"
DECK_NAMES = (
    "Accomplished Alchemist", "Angels", "Anti-Lifegain", "Auras",
    "Breaching Dragonstorm", "Bruna", "Colossus Hammer", "Creature Giving",
    "Critter Lifegain", "Dragons", "Dragonstorm", "Eldrazi Displacer Flicker",
    "Extra Turns", "Five Colour", "Fluctuator", "Fungus", "Galadriel",
    "Giants", "Goblins", "Gods", "Hinata", "Hydras", "Jumbo Cactuar",
    "Kithkin", "Kitty Equipment", "Knights", "Landfall", "Landfall Elementals",
    "Lifegain Heliod Combo", "Martyr Lifegain", "Melira Pod", "Merfolk",
    "Midrange Burn", "Mill", "Minotaur", "Mirrorwing Dragon", "Modern RW Burn",
    "Morph", "NivMizzetCombo", "Pirates", "Prevent Damage", "Selesnya Lifegain",
    "Shadowborn Apostle", "Snow", "Soldiers", "Spirits", "Stompy Surprise",
    "Unpredictable Cyclone", "Vampires", "White Knights",
)


def render():
    if len(DECK_NAMES) != 50 or len(set(DECK_NAMES)) != 50:
        raise ValueError("opponent pool manifest must contain 50 unique decks")
    paths = [ROOT / "decks" / name / f"{name}.cod" for name in DECK_NAMES]
    lines = [
        "#pragma once",
        "// Generated by scripts/generate_opponent_deck_pool.py from the 50 primary decklists.",
        "// Update with that script after editing a primary list; sideboards are excluded.",
        "#include <array>",
        "#include <utility>",
        "#include <vector>",
        "",
        "namespace opponentdeck {",
        "struct DeckSpec { const char* name; std::vector<std::pair<const char*, int>> cards; };",
        "inline const std::array<DeckSpec, 50>& Pool()",
        "{",
        "    static const std::array<DeckSpec, 50> kPool = {{",
    ]
    for path in paths:
        cards = ET.parse(path).getroot().findall("./zone[@name='main']/card")
        total = sum(int(card.get("number", "1")) for card in cards)
        if total != 60:
            raise ValueError(f"{path.relative_to(ROOT)}: expected 60 mainboard cards, found {total}")
        lines.append(f"        {{{json.dumps(path.parent.name, ensure_ascii=False)}, {{")
        for card in cards:
            name = card.get("name")
            count = int(card.get("number", "1"))
            if not name or count <= 0:
                raise ValueError(f"{path.relative_to(ROOT)}: invalid card entry")
            lines.append(f"            {{{json.dumps(name, ensure_ascii=False)}, {count}}},")
        lines.append("        }},")
    lines += ["    }};", "    return kPool;", "}", "} // namespace opponentdeck", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            sys.exit(f"{OUTPUT.relative_to(ROOT)} is stale; run {Path(__file__).name}")
    else:
        OUTPUT.write_text(content)


if __name__ == "__main__":
    main()
