#!/usr/bin/env python3
"""Expose the authoritative Claude Markdown skills to Codex without copying bodies."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MARKER = '<!-- Generated by scripts/sync_codex_skills.py; edit the Claude source. -->'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated entrypoints are out of sync')
    args = parser.parse_args()
    source_dir = ROOT / '.claude/skills'
    target_dir = ROOT / '.agents/skills'
    sources = {p.stem: p for p in source_dir.glob('*.md')}
    expected = {}
    for name, source in sorted(sources.items()):
        paragraphs = source.read_text().split('\n\n')
        description = next(p for p in paragraphs if not p.startswith('#'))
        description = re.sub(r'\s+', ' ', description).replace('**', '').replace('`', '')
        if len(description) > 450:
            description = description[:447].rsplit(' ', 1)[0] + '...'
        target = target_dir / name / 'SKILL.md'
        if target.exists() and MARKER not in target.read_text():
            raise SystemExit(f'Refusing to overwrite unmanaged skill: {target}')
        expected[target] = (
            f'---\nname: {name}\ndescription: {json.dumps(description)}\n---\n\n'
            f'{MARKER}\n\n'
            f'Read `.claude/skills/{source.name}` from the repository root in full, '
            'then follow it for this task. This is the authoritative source; '
            'resolve its repository paths from the repository root.\n'
        )
        if not args.check:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(expected[target])
    stale = []
    for target in target_dir.glob('*/SKILL.md'):
        if target.parent.name not in sources and MARKER in target.read_text():
            if args.check:
                stale.append(str(target.relative_to(ROOT)))
            else:
                target.unlink()
                if not any(target.parent.iterdir()):
                    target.parent.rmdir()
    if args.check:
        stale.extend(str(target.relative_to(ROOT)) for target, content in expected.items()
                     if not target.exists() or target.read_text() != content)
        if stale:
            raise SystemExit('Codex skill entrypoints out of sync: ' + ', '.join(sorted(stale)))
        print(f'Checked {len(sources)} Codex skill entrypoints: in sync.')
    else:
        print(f'Synchronized {len(sources)} Codex skill entrypoints.')


if __name__ == '__main__':
    main()
