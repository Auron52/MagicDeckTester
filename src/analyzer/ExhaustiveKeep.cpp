void RunExhaustiveKeep(std::ostream& os, const Decklist& deck, const MulliganProfile& profile,
                       const ExhaustiveKeepConfig& cfg)
{
    // ---- 1. Buckets (objective-relative equivalence) --------------------------------------------
    // Bucketing uses the FIXED equiv_seed (not the rollout seed) so the clustering is byte-identical
    // across machines -- a precondition for pooling their raw tables.
    const auto t_bucket = std::chrono::steady_clock::now();
    // Discovery CACHE (MTG_EQUIV_CACHE=<path>): the equivalence classes are a deterministic function of
    // (deck cards, probes, depth, budget_ms, threshold, equiv_seed, max_turns, play commit), yet the
    // chunked gen re-invokes the analyzer once PER ROUND with identical params -- so every round otherwise
    // re-derives the same (minutes-long) bucketing. Fingerprint-gate a JSON cache: a hit skips discovery;
    // any spec/commit change re-discovers and overwrites. Absent -> unchanged (always discovers).
    EquivReport eq;
    uint64_t eq_deck_fp = 1469598103934665603ULL;
    {
        std::vector<std::string> dn;
        for (const Card& c : deck.mainboard) { dn.push_back(c.m_name.str()); }
        std::sort(dn.begin(), dn.end());
        for (const std::string& n : dn) { eq_deck_fp = Fnv(n + ",", eq_deck_fp); }
    }
    const std::string eq_commit = []{ const char* s = std::getenv("MTG_COMMIT"); return s ? std::string(s) : std::string(); }();
    const long long   eq_thr_x1e6 = static_cast<long long>(std::llround(cfg.threshold * 1e6));
    const char*       eq_cache    = std::getenv("MTG_EQUIV_CACHE");
    bool eq_loaded = false;
    if (eq_cache && *eq_cache && std::filesystem::exists(eq_cache))
    {
        std::ifstream cf(eq_cache);
        nlohmann::json cj; bool ok = true;
        try { cf >> cj; } catch (...) { ok = false; }
        if (ok && cj.contains("meta") && cj.contains("classes"))
        {
            const auto& m = cj["meta"];
            const bool match = m.value("deck_fp", 0ULL) == eq_deck_fp
                            && m.value("probes", -1) == cfg.probes
                            && m.value("depth", -1) == cfg.depth
                            && m.value("budget_ms", -1) == cfg.budget_ms
                            && m.value("threshold_x1e6", ~0LL) == eq_thr_x1e6
                            && m.value("equiv_seed", ~0ULL) == cfg.equiv_seed
                            && m.value("max_turns", -1) == cfg.max_turns
                            && m.value("commit", std::string("\x01")) == eq_commit;
            if (match)
            {
                eq.probes         = m.value("probes", 0);
                eq.distinct_cards = m.value("distinct_cards", 0);
                for (const auto& jc : cj["classes"])
                {
                    EquivClass ec;
                    ec.members   = jc.value("members", std::vector<std::string>{});
                    ec.signature = jc.value("signature", std::vector<int>{});
                    eq.classes.push_back(std::move(ec));
                }
                eq_loaded = true;
                std::cerr << "[keepgen] equivalence discovery: CACHE HIT (" << eq.classes.size()
                          << " buckets from " << eq_cache << ") -- skipped\n" << std::flush;
            }
            else
            { std::cerr << "[keepgen] equivalence cache " << eq_cache
                        << " fingerprint MISMATCH -- re-discovering\n" << std::flush; }
        }
    }
    if (!eq_loaded)
    {
        std::cerr << "[keepgen] equivalence discovery: " << cfg.probes << " probes, depth " << cfg.depth
                  << " ...\n" << std::flush;
        eq = DiscoverEquivalence(deck, profile, cfg.probes, cfg.depth, cfg.budget_ms,
                                 cfg.threshold, cfg.equiv_seed, cfg.max_turns);
        std::cerr << "[keepgen] equivalence discovery done: " << eq.classes.size() << " raw buckets ("
                  << static_cast<long long>(std::chrono::duration<double>(
                         std::chrono::steady_clock::now() - t_bucket).count()) << "s)\n" << std::flush;
        if (eq_cache && *eq_cache)
        {
            nlohmann::json cj;
            cj["meta"] = { {"deck_fp", eq_deck_fp}, {"probes", cfg.probes}, {"depth", cfg.depth},
                           {"budget_ms", cfg.budget_ms}, {"threshold_x1e6", eq_thr_x1e6},
                           {"equiv_seed", cfg.equiv_seed}, {"max_turns", cfg.max_turns},
                           {"commit", eq_commit}, {"distinct_cards", eq.distinct_cards} };
            nlohmann::json jclasses = nlohmann::json::array();
            for (const EquivClass& ec : eq.classes)
            { jclasses.push_back({ {"members", ec.members}, {"signature", ec.signature} }); }
            cj["classes"] = std::move(jclasses);
            const std::string tmp = std::string(eq_cache) + ".tmp";
            { std::ofstream of(tmp); of << cj.dump(); }
            std::error_code wec; std::filesystem::rename(tmp, eq_cache, wec);
            if (!wec) { std::cerr << "[keepgen] equivalence cache WROTE " << eq_cache << "\n" << std::flush; }
        }
    }

    // MANUAL force-merge (MTG_EQUIV_FORCE_MERGE): union the classes containing each ";"-group's cards into
    // one bucket. Deliberate near-equivalent collapse (e.g. the fetchlands) the strict distance threshold
    // won't do. Applied to eq.classes BEFORE anything downstream (counts, tables, bucket_fp) so pooling
    // parity is preserved: chunks with the same spec share the fingerprint; a different spec won't pool.
    if (!cfg.force_merge.empty())
    {
        auto split = [](const std::string& s, char d) {
            std::vector<std::string> out; std::string cur;
            for (char c : s) { if (c == d) { if (!cur.empty()) out.push_back(cur); cur.clear(); } else cur += c; }
            if (!cur.empty()) out.push_back(cur);
            return out; };
        auto trim = [](std::string s) {
            std::size_t a = s.find_first_not_of(" \t"); std::size_t b = s.find_last_not_of(" \t");
            return (a == std::string::npos) ? std::string() : s.substr(a, b - a + 1); };
        std::vector<char> removed(eq.classes.size(), 0);
        for (const std::string& grp : split(cfg.force_merge, ';'))
        {
            int keep_cls = -1;
            for (const std::string& raw : split(grp, ','))
            {
                const std::string nm = trim(raw);
                if (nm.empty()) { continue; }
                // Match the full member name OR its pre-comma segment, so a card whose name CONTAINS a
                // comma (e.g. "Karrthus, Tyrant of Jund", "Lathliss, Dragon Queen") is addressable by its
                // leading name ("Karrthus", "Lathliss") -- the group delimiter is ',' so the full comma
                // name can't be written literally. Comma-free names still match exactly (unchanged).
                int found = -1;
                for (std::size_t c = 0; c < eq.classes.size(); ++c)
                    if (!removed[c])
                        for (const std::string& mem : eq.classes[c].members)
                            if (mem == nm || mem.substr(0, mem.find(',')) == nm)
                            { found = static_cast<int>(c); break; }
                if (found < 0) { std::cerr << "[keepgen]   force-merge: card not found: '" << nm << "'\n"; continue; }
                if (keep_cls < 0) { keep_cls = found; }
                else if (found != keep_cls)
                {
                    for (const std::string& mem : eq.classes[found].members)
                    { eq.classes[keep_cls].members.push_back(mem); }
                    removed[found] = 1;
                }
            }
        }
        std::vector<EquivClass> kept;
        for (std::size_t c = 0; c < eq.classes.size(); ++c) if (!removed[c]) kept.push_back(eq.classes[c]);
        eq.classes = std::move(kept);
        std::cerr << "[keepgen] force-merge applied: -> " << eq.classes.size() << " buckets\n" << std::flush;
    }
    const int K = static_cast<int>(eq.classes.size());

    std::map<std::string, int> bucket_of;             // card name -> bucket index
    std::vector<int>  count(K, 0);                    // deck copies in each bucket
    std::vector<Card> rep(K);                         // a representative Card per bucket
    std::vector<std::string> label(K);
    for (int b = 0; b < K; ++b)
    {
        for (const std::string& nm : eq.classes[b].members) { bucket_of[nm] = b; }
        label[b] = eq.classes[b].members.front()
                 + (eq.classes[b].members.size() > 1
                      ? " (+" + std::to_string(eq.classes[b].members.size() - 1) + ")" : "");
    }
    for (const Card& c : deck.mainboard)
    {
        auto it = bucket_of.find(c.m_name.str());
        if (it == bucket_of.end()) { continue; }
        count[it->second]++;
        if (rep[it->second].m_name.str().empty()) { rep[it->second] = c; }
    }

    // Execution-trace (MTG_KEEP_TRACE): compact index of every distinct card NAME in the deck, and the
    // per-rollout "touched" recording it enables. Off => no out_hit passed => engine byte-identical.
    const bool trace_on = []{ const char* s = std::getenv("MTG_KEEP_TRACE"); return s && *s && std::string(s) != "0"; }();
    std::map<std::string, int> touch_index;
    std::vector<std::string>   touch_names;
    if (trace_on)
        for (const Card& c : deck.mainboard)
            if (touch_index.emplace(c.m_name.str(), static_cast<int>(touch_names.size())).second)
            { touch_names.push_back(c.m_name.str()); }

    // ---- 2. Enumerate hand compositions for sizes HAND .. HAND-max_mull --------------------------
    const int min_size = std::max(1, HAND - cfg.max_mull);
    std::vector<SizeTable> tables(HAND - min_size + 1);   // tables[HAND-H] holds the size-H table
    auto TB = [&](int H) -> SizeTable& { return tables[HAND - H]; };   // vector: concurrent-safe reads
    for (int H = HAND; H >= min_size; --H)
    {
        SizeTable t;
        std::vector<int> cap(K), cur(K, 0);
        for (int b = 0; b < K; ++b) { cap[b] = std::min(count[b], H); }
        EnumComps(0, H, cur, cap, t.comps);
        for (int i = 0; i < static_cast<int>(t.comps.size()); ++i) { t.index[t.comps[i]] = i; }
        t.V.assign(t.comps.size(), { 0.0, 0.0 });
        t.se.assign(t.comps.size(), { 0.0, 0.0 });
        t.sum.assign(t.comps.size(), { 0.0, 0.0 });
        t.sumsq.assign(t.comps.size(), { 0.0, 0.0 });
        t.cnt.assign(t.comps.size(), { 0, 0 });
        if (trace_on) { t.touched.assign(t.comps.size(), {}); }
        TB(H) = std::move(t);
    }

    os << "=== EXHAUSTIVE KEEP (deck=" << deck.mainboard.size() << " cards, " << K << " buckets) ===\n";
    for (int b = 0; b < K; ++b) { os << "  [" << b << "] " << label[b] << " x" << count[b] << "\n"; }
    os << "distinct hands:";
    long long total_hands = 0;
    for (int H = HAND; H >= min_size; --H)
    { os << " size" << H << "=" << TB(H).comps.size(); total_hands += TB(H).comps.size(); }
    os << "  (total " << total_hands << ")\n";
    os << "rollouts/hand R=" << cfg.rollouts << ", depth=" << cfg.depth
       << ", horizon=" << cfg.max_turns << "\n" << std::flush;

    // ---- 3. Evaluate V[H][comp][pd] via R reshuffled continuations (parallel over work items) -----
    MulliganProfile rollout_profile = profile;
    rollout_profile.keep_model = KeepModel{};
    const bool second_main = GoldFishRunner::DeckUsesSecondMain(deck);

    struct Work { int H; int idx; };
    std::vector<Work> work;
    // work_idx[HAND-H][idx] = w -- reverse map so refinement can find a cell's work index (and thus its
    // rollout seed stream) from (H,idx). The seed uses w, so this map keeps adaptive rollouts on the
    // SAME seed stream a uniform run would use => r_floor==rollouts is byte-identical.
    std::vector<std::vector<int>> work_idx(tables.size());
    for (int H = HAND; H >= min_size; --H)
    {
        work_idx[HAND - H].assign(TB(H).comps.size(), -1);
        for (int i = 0; i < static_cast<int>(TB(H).comps.size()); ++i)
        { work_idx[HAND - H][i] = static_cast<int>(work.size()); work.push_back({ H, i }); }
    }

    const std::map<std::string, int>& bof = bucket_of;   // const ref -> concurrent-safe find()

    // ---- Cross-run PRUNE-SET consume / carry-forward (MTG_KEEP_PRUNE_SET) ------------------------
    // A prior run's prune-set lists size-7 cells that were CONFIDENT MULLIGANS (see the emit path in
    // RunKeepMerge). Two uses, one mechanism -- carry that judgement forward so this run doesn't re-
    // establish the obvious mulligans:
    //   (a) MULTI-CHUNK POOLING (same commit): skip the junk cells in later chunks so the budget lands on
    //       the near-threshold cells; frozen cells' counts come from the earlier chunks at merge.
    //   (b) REGENERATION on a NEW COMMIT (same decklist): reuse last run's confident-mull set so a re-run
    //       (e.g. after a play-logic fix) skips them instead of re-paying their floor pass. This is the
    //       "don't re-run the multi-day deck from scratch" lever. bucket_fp/deck_fp are identical for the
    //       same list, and play_digest/commit are deliberately NOT gated, so a new-commit prune-set is
    //       accepted; the values are stale-commit but a confident mull's value only enters as
    //       min(V,Dopt_new[1])==Dopt_new[1] (Dopt is recomputed fresh from this run's smaller tables).
    //
    // MTG_KEEP_CARRY_MODE selects the fidelity posture (default "verify"):
    //   * verify  -- carried cells start at a REDUCED floor (MTG_KEEP_CARRY_FLOOR, default 2) instead of
    //                being skipped, and are refinable. The adaptive gate is curse-safe (an under-sampled
    //                cell reads LOWER -> looks more keepable -> gets refined), so any hand that FLIPPED to
    //                keepable on the new deck/commit is caught and promoted. Fidelity-preserving; still
    //                saves most of the junk floor. Poolable (real fresh samples). Requires an adaptive run
    //                (a uniform run has no refiner to catch a flip -> carried cells are sampled in full).
    //   * skip    -- carried cells get ZERO rollouts and their prior value is preloaded (asserted MULL).
    //                Max saving. EXACTLY policy-preserving for use (a) [min(V,Dopt[1])==Dopt[1] can't move
    //                Dopt or keep flags, and the pool supplies the real counts]. For use (b) it is a
    //                fidelity BET: a large enough deck/play change could lift the threshold above a carried
    //                hand's true new value, and a hard skip would silently keep it as MULL. Use for a
    //                stable list where the junk is structural (0-land / all-land / off-colour floods).
    //
    // Correctness invariants (both modes): the work vector is left INTACT (a carried cell keeps its work
    // index w, so every OTHER cell's rollout seed stream is byte-identical to an uncarried run); skip sets
    // only t.V (recompute() skips cnt==0 so the preloaded V survives; the raw emits count=0 -> no samples
    // carried into this run's sidecar -> use-(a) pooling takes counts from the earlier chunks, no double-
    // count; per-pd exact). Fingerprints (bucket/deck/equiv_seed/K/max_mull) are checked -- REFUSE on
    // mismatch (a changed decklist changes bucket/deck_fp -> a modified-list carry is a separate feature).
    std::vector<std::array<bool, 2>> frozen7(TB(HAND).comps.size(),   { false, false });  // skip cells
    std::vector<std::array<bool, 2>> carry_lowfloor7(TB(HAND).comps.size(), { false, false });  // verify cells
    // Phase 2 sub-table freeze: a size-(7-m) sub-hand whose value is confidently ABOVE its keep-bar
    // Dopt[m+1] is never a KEEP's bottoming argmin (a hand bottoming into it has keep_val > Dopt -> it
    // mulligans), so skipping its rollouts is decision-preserving. frozen_sub[H][idx][pd], H=1..HAND-1.
    std::vector<std::vector<std::array<bool, 2>>> frozen_sub(HAND);
    for (int H = 1; H < HAND; ++H) { frozen_sub[H].assign(TB(H).comps.size(), { false, false }); }
    long long carry_floor = []{ const char* s = std::getenv("MTG_KEEP_CARRY_FLOOR");
        return (s && *s) ? std::max<long long>(1, std::strtoll(s, nullptr, 10)) : 2LL; }();
    const bool carry_skip = []{ const char* s = std::getenv("MTG_KEEP_CARRY_MODE");
        return s && std::string(s) == "skip"; }();   // default (unset / "verify") => verify
    if (const char* ps = std::getenv("MTG_KEEP_PRUNE_SET"); ps && *ps)
    {
        std::ifstream pf(ps);
        if (!pf) { std::cerr << "[keepgen] PRUNE-SET: cannot open " << ps << " -- ignoring\n" << std::flush; }
        else
        {
            nlohmann::json pj;
            bool parsed = true;
            try { pf >> pj; }
            catch (const std::exception& e)
            { std::cerr << "[keepgen] PRUNE-SET: bad json (" << e.what() << ") -- ignoring\n" << std::flush; parsed = false; }
            if (parsed && pj.contains("meta") && pj.contains("frozen"))
            {
                // Fingerprints must match, else the frozen comps index a different bucket map / deck and
                // we'd carry the wrong cells. REFUSE on any mismatch (do not silently mis-apply).
                uint64_t my_bucket_fp = 1469598103934665603ULL;
                for (int b = 0; b < K; ++b)
                { my_bucket_fp = Fnv("|", my_bucket_fp);
                  for (const std::string& n : eq.classes[b].members) { my_bucket_fp = Fnv(n + ",", my_bucket_fp); } }
                std::vector<std::string> dn;
                for (const Card& c : deck.mainboard) { dn.push_back(c.m_name.str()); }
                std::sort(dn.begin(), dn.end());
                uint64_t my_deck_fp = 1469598103934665603ULL;
                for (const std::string& n : dn) { my_deck_fp = Fnv(n + ",", my_deck_fp); }
                const auto& m = pj["meta"];
                const bool ok = m.value("bucket_fp", 0ULL) == my_bucket_fp
                             && m.value("deck_fp", 0ULL) == my_deck_fp
                             && m.value("equiv_seed", 0ULL) == cfg.equiv_seed
                             && m.value("K", -1) == K
                             && m.value("max_mull", -1) == cfg.max_mull;
                if (!ok)
                {
                    std::cerr << "[keepgen] PRUNE-SET: fingerprint mismatch "
                                 "(bucket/deck/equiv_seed/K/max_mull) -- REFUSING to apply " << ps << "\n" << std::flush;
                }
                else
                {
                    SizeTable& t7 = TB(HAND);
                    long long n_carried = 0;
                    long long n_carried_sub = 0;
                    for (const auto& e : pj["frozen"])
                    {
                        const std::vector<int> comp = e["comp"].get<std::vector<int>>();
                        const int pd = e.value("pd", -1);
                        if (pd != 0 && pd != 1) { continue; }
                        const long long c = e.value("count", 0LL);
                        if (c <= 0) { continue; }
                        const int H = e.value("size", HAND);   // sub-table entries carry "size"<7; size-7 default
                        if (H == HAND)
                        {
                            auto it = t7.index.find(comp);
                            if (it == t7.index.end()) { continue; }
                            const int idx = it->second;
                            if (frozen7[idx][pd] || carry_lowfloor7[idx][pd]) { continue; }
                            if (carry_skip)
                            {
                                frozen7[idx][pd] = true;
                                t7.V[idx][pd]    = e["sum"].get<double>() / static_cast<double>(c);  // preload V only
                            }
                            else { carry_lowfloor7[idx][pd] = true; }   // verify: reduced floor, refinable
                            ++n_carried;
                        }
                        else if (H >= 1 && H < HAND && carry_skip)   // sub-table freeze (skip mode only)
                        {
                            SizeTable& ts = TB(H);
                            auto it = ts.index.find(comp);
                            if (it == ts.index.end()) { continue; }
                            const int idx = it->second;
                            if (frozen_sub[H][idx][pd]) { continue; }
                            frozen_sub[H][idx][pd] = true;
                            ts.V[idx][pd] = e["sum"].get<double>() / static_cast<double>(c);  // preload high V
                            ++n_carried_sub;
                        }
                    }
                    std::cerr << "[keepgen] PRUNE-SET: carried " << n_carried << " size-7 + " << n_carried_sub
                              << " sub-table cell-sides ("
                              << (carry_skip ? "skip mode -- 0 rollouts, asserted decision (keep/mull)"
                                             : ("verify mode -- reduced floor " + std::to_string(carry_floor) + ", refinable"))
                              << ") from " << ps << " (source_R=" << m.value("source_R", 0)
                              << ", prune_eps=" << m.value("prune_eps", 0.0) << ")\n" << std::flush;
                }
            }
        }
    }

    // Rollout-config play digest -- the pooling identity stamped into both the runtime policy and the
    // raw sidecar below. Computed ONCE here (a fixed 64-game d5/b20 battery) rather than just before the
    // writes, because the change-detection carry (below) needs it now: a prior whose play_digest matches
    // this run's is byte-identical play, so its ENTIRE table is reusable with zero fresh rollouts.
    std::string play_digest;
    if (!cfg.out_profile.empty() || !cfg.out_raw.empty())
    {
        play_digest = RolloutConfigDigest(deck, profile, cfg.depth, cfg.budget_ms, cfg.max_turns);
        os << "rollout-config play digest (d" << cfg.depth << "/b" << cfg.budget_ms
           << ", 64-game battery): " << play_digest << "\n";
    }

    // ---- Change-detection carry (MTG_KEEP_PRIOR_RAW) ---------------------------------------------
    // Whole-pool warm-start: given a PRIOR pool (from a previous run, typically an older commit, same
    // decklist), re-sample every cell only THINLY at the floor and then spend the refine budget ONLY on
    // the cells the change actually MOVED -- detected by comparing this run's thin floor estimate to the
    // prior. Unmoved cells reuse the prior's (higher-R) value; moved cells are refined fresh. This scopes
    // a re-run to what the change touched without needing to know what changed. See
    // docs/design/change-detection-carry.md. Rule-0 refinement: a play change only invalidates the cells
    // whose rollouts hit the changed code; an unmoved cell's prior value is not stale, it is the same
    // number. The ONLY risk is a false negative (miss a real move), so the test is biased toward MOVED.
    std::vector<std::vector<std::array<double, 2>>>    pri_V(tables.size()), pri_var(tables.size());
    std::vector<std::vector<std::array<long long, 2>>> pri_n(tables.size());
    std::vector<std::vector<std::array<bool, 2>>>      has_prior(tables.size()), resolved(tables.size());
    for (int H = HAND; H >= min_size; --H)
    {
        const std::size_t n = TB(H).comps.size();
        pri_V[HAND - H].assign(n, { 0.0, 0.0 });     pri_var[HAND - H].assign(n, { 0.0, 0.0 });
        pri_n[HAND - H].assign(n, { 0, 0 });         has_prior[HAND - H].assign(n, { false, false });
        resolved[HAND - H].assign(n, { false, false });
    }
    bool   change_detect = false;
    double detect_delta  = []{ const char* s = std::getenv("MTG_KEEP_DETECT_DELTA");
        return (s && *s) ? std::max(0.0, std::atof(s)) : 0.10; }();   // decision-relevant win-turn shift
    double detect_z      = []{ const char* s = std::getenv("MTG_KEEP_DETECT_Z");
        return (s && *s) ? std::max(0.0, std::atof(s)) : 1.64; }();   // CI band for the "unmoved" call
    // EXECUTION-TRACE reuse (MTG_KEEP_CHANGED_CARDS): the set of cards a change touched. A prior cell
    // whose recorded touched-set is DISJOINT from this set is byte-identical on the new commit -> reuse
    // its prior value EXACTLY (0 samples of refine), including near-threshold + bottoming cells that the
    // statistical test can't clear. Requires a TRACED prior (its entries carry "touched").
    std::set<std::string> changed_cards;
    if (const char* cc = std::getenv("MTG_KEEP_CHANGED_CARDS"); cc && *cc)
    {
        std::string s = cc, cur;
        for (char ch : s) { if (ch == ',') { if (!cur.empty()) changed_cards.insert(cur); cur.clear(); } else cur += ch; }
        if (!cur.empty()) { changed_cards.insert(cur); }
    }
    std::vector<std::vector<char>> trace_reuse(tables.size());   // per (H-idx, cell): prior disjoint from changed
    long long n_trace_reuse = 0; bool prior_traced = false;
    // Set true below when the prior is reused WHOLESALE (identical play_digest). Hoisted to this scope so
    // Pass A can skip the throwaway floor sample on every reused cell (its value comes from the prior).
    bool reuse_all_cells = false;
    if (const char* pr = std::getenv("MTG_KEEP_PRIOR_RAW"); pr && *pr)
    {
        std::ifstream prf(pr);
        if (!prf) { std::cerr << "[keepgen] PRIOR-RAW: cannot open " << pr << " -- ignoring\n" << std::flush; }
        else
        {
            nlohmann::json pj; bool parsed = true;
            try { prf >> pj; } catch (const std::exception& e)
            { std::cerr << "[keepgen] PRIOR-RAW: bad json (" << e.what() << ") -- ignoring\n" << std::flush; parsed = false; }
            if (parsed && pj.contains("meta") && pj.contains("sizes"))
            {
                uint64_t my_bucket_fp = 1469598103934665603ULL;
                for (int b = 0; b < K; ++b)
                { my_bucket_fp = Fnv("|", my_bucket_fp);
                  for (const std::string& n : eq.classes[b].members) { my_bucket_fp = Fnv(n + ",", my_bucket_fp); } }
                std::vector<std::string> dnn;
                for (const Card& c : deck.mainboard) { dnn.push_back(c.m_name.str()); }
                std::sort(dnn.begin(), dnn.end());
                uint64_t my_deck_fp = 1469598103934665603ULL;
                for (const std::string& n : dnn) { my_deck_fp = Fnv(n + ",", my_deck_fp); }
                const auto& mm = pj["meta"];
                // EXTEND-DEPTH: a prior with max_mull <= this run's may seed it. The prior supplies its
                // sizes 7..7-prior_mm; the DEEPER sizes it lacks are rolled fresh, then BuildPolicy runs at
                // the run's (deeper) max_mull. A shallower prior is a strict subset (same buckets/deck/
                // equiv_seed/K), so pooling parity holds. (prior_mm > cfg.max_mull would need DROPPING
                // sizes and is not supported here.)
                const int prior_mm = mm.value("max_mull", -1);
                const bool ok = mm.value("bucket_fp", 0ULL) == my_bucket_fp
                             && mm.value("deck_fp", 0ULL) == my_deck_fp
                             && mm.value("equiv_seed", 0ULL) == cfg.equiv_seed
                             && mm.value("K", -1) == K
                             && prior_mm >= 0 && prior_mm <= cfg.max_mull;
                if (!ok)
                { std::cerr << "[keepgen] PRIOR-RAW: fingerprint mismatch (bucket/deck/equiv_seed/K/max_mull)"
                               " -- REFUSING (a changed decklist needs bucket translation, not yet built)\n" << std::flush; }
                else if (!(cfg.r_floor > 0 && cfg.r_floor < cfg.rollouts))
                { std::cerr << "[keepgen] PRIOR-RAW: change-detection needs an ADAPTIVE run "
                               "(0 < MTG_KEEP_R_FLOOR < MTG_KEEP_ROLLOUTS) -- ignoring prior\n" << std::flush; }
                else
                {
                    prior_traced = mm.value("traced", false);
                    if (prior_mm < cfg.max_mull)
                    { std::cerr << "[keepgen] EXTEND-DEPTH: prior max_mull=" << prior_mm << " -> this run "
                                << cfg.max_mull << "; sizes " << HAND << ".." << (HAND - prior_mm)
                                << " reuse from prior, sizes " << (HAND - prior_mm - 1)
                                << "..1 roll fresh\n" << std::flush; }

                    // ---- Phase B AUTO-ATTRIBUTION + ENGINE GUARD --------------------------------------
                    // When the operator did NOT declare MTG_KEEP_CHANGED_CARDS, derive the reuse scope
                    // automatically from the prior's stored provenance (meta.play_digest / engine_fp /
                    // card_defs) vs this build + cards.json:
                    //   1. play_digest UNCHANGED  -> byte-identical play -> reuse the ENTIRE prior pool.
                    //   2. play_digest changed, engine_fp MATCHES, some card DEFS changed -> card-level
                    //      trace reuse scoped to those cards (the existing disjointness path).
                    //   3. play_digest changed, engine_fp DIFFERS/unavailable -> engine (shared-code)
                    //      change can move any cell -> REFUSE card-level reuse; statistical only.
                    // A manual MTG_KEEP_CHANGED_CARDS always wins (human-in-the-loop override).
                    const bool manual_changed = !changed_cards.empty();
                    const std::string prior_pd = mm.value("play_digest", std::string());
                    // Coarse reuse: play_digest IS the pooling identity, so an identical digest proves
                    // byte-identical play and every prior cell reproduces exactly on this build -> reuse the
                    // ENTIRE prior pool (0 fresh rollouts on reused cells). Checked OUTSIDE the card_defs
                    // guard so a MERGE-output prior (carries play_digest but not card_defs) also qualifies --
                    // this is what lets it seed a deeper-max_mull EXTEND run.
                    if (!manual_changed && !prior_pd.empty() && prior_pd == play_digest)
                    {
                        reuse_all_cells = true;
                        std::cerr << "[keepgen] AUTO-ATTRIB: play_digest unchanged -> reuse the ENTIRE"
                                     " prior pool (0 fresh rollouts on reused cells)\n" << std::flush;
                    }
                    // Finer reuse (play_digest DIFFERS): if the engine is unchanged, scope reuse to the cards
                    // whose defs moved; else fall back to statistical change-detection only.
                    else if (!manual_changed && mm.contains("card_defs"))
                    {
                        const std::string prior_efp = mm.value("engine_fp", std::string());
                        const std::string cur_efp   = MTG_ENGINE_FP;
                        const bool engine_ok = !prior_efp.empty() && !cur_efp.empty() && prior_efp == cur_efp;
                        if (engine_ok)
                        {
                            const auto& cd = mm["card_defs"];
                            std::set<std::string> distinct;
                            for (const Card& c : deck.mainboard) { distinct.insert(c.m_name.str()); }
                            for (const std::string& n : distinct)
                            {
                                const uint64_t cur = CardDatabase::Instance().DefHash(n);
                                const uint64_t prv = cd.contains(n) ? cd[n].get<uint64_t>() : ~0ULL;
                                if (cur != prv) { changed_cards.insert(n); }
                            }
                            if (changed_cards.empty())
                            { std::cerr << "[keepgen] AUTO-ATTRIB: play_digest changed but engine_fp AND all"
                                           " card defs match -- unexpected; REFUSING card-level reuse"
                                           " (statistical only)\n" << std::flush; }
                            else
                            { std::cerr << "[keepgen] AUTO-ATTRIB: engine_fp matches; " << changed_cards.size()
                                        << " card def(s) changed {"
                                        << [&]{ std::string s; for (const auto& c : changed_cards) { s += (s.empty()?"":",") + c; } return s; }()
                                        << "} -> card-level trace reuse\n" << std::flush; }
                        }
                        else
                        {
                            std::cerr << "[keepgen] AUTO-ATTRIB: play_digest changed and engine_fp "
                                      << ((prior_efp.empty() || cur_efp.empty()) ? "unavailable" : "differs")
                                      << " -- engine change; REFUSING card-level reuse (statistical only)\n" << std::flush;
                        }
                    }

                    const bool trace_active = reuse_all_cells || !changed_cards.empty();
                    if (!reuse_all_cells && !changed_cards.empty() && !prior_traced)
                    { std::cerr << "[keepgen] CHANGED-CARDS set but prior is NOT traced (no per-cell touched"
                                   " sets) -- falling back to statistical change-detection only\n" << std::flush; }
                    for (int H = HAND; H >= min_size; --H) { trace_reuse[HAND - H].assign(TB(H).comps.size(), 0); }
                    long long loaded = 0;
                    for (const auto& sz : pj["sizes"])
                    {
                        const int H = sz.value("H", 0);
                        if (H > HAND || H < min_size) { continue; }
                        SizeTable& t = TB(H);
                        for (const auto& e : sz["entries"])
                        {
                            auto it = t.index.find(e["comp"].get<std::vector<int>>());
                            if (it == t.index.end()) { continue; }
                            const int i = it->second;
                            // reuse-all (play_digest identical): every cell reuses the prior exactly; the
                            // per-cell touched set is irrelevant (no card/engine change to scope against).
                            if (reuse_all_cells) { trace_reuse[HAND - H][i] = 1; ++n_trace_reuse; }
                            // Execution-trace: disjoint from the changed cards => provably unmoved => reuse.
                            else if (trace_active && prior_traced && e.contains("touched"))
                            {
                                bool disjoint = true;
                                for (const auto& nm : e["touched"])
                                    if (changed_cards.count(nm.get<std::string>())) { disjoint = false; break; }
                                if (disjoint) { trace_reuse[HAND - H][i] = 1; ++n_trace_reuse; }
                            }
                            if (!e.contains("sumsq")) { continue; }   // need variance for the statistical test
                            for (int pd = 0; pd < 2; ++pd)
                            {
                                const long long c = e["count"][pd].get<long long>();
                                if (c < 2) { continue; }
                                const double s = e["sum"][pd].get<double>();
                                const double sq = e["sumsq"][pd].get<double>();
                                const double V = s / c;
                                pri_V[HAND - H][i][pd]     = V;
                                pri_var[HAND - H][i][pd]   = std::max(0.0, sq / c - V * V);
                                pri_n[HAND - H][i][pd]     = c;
                                has_prior[HAND - H][i][pd] = true;
                                ++loaded;
                            }
                        }
                    }
                    if (reuse_all_cells)
                    { std::cerr << "[keepgen] EXECUTION-TRACE: " << n_trace_reuse
                                << " cells reused from the identical-play prior (whole-pool)\n" << std::flush; }
                    else if (trace_active && prior_traced)
                    { std::cerr << "[keepgen] EXECUTION-TRACE: " << n_trace_reuse << " cells provably untouched by {"
                                << [&]{ std::string s; for (const auto& c : changed_cards) { s += (s.empty()?"":",") + c; } return s; }()
                                << "} -> reuse prior exactly\n" << std::flush; }
                    change_detect = true;
                    std::cerr << "[keepgen] PRIOR-RAW: loaded " << loaded << " prior cell-sides from " << pr
                              << " (source_R=" << mm.value("R", 0) << ", detect_delta=" << detect_delta
                              << ", detect_z=" << detect_z << ") -- change-detection ON\n" << std::flush;
                }
            }
        }
    }

    // Append rollouts [r0,r1) to cell `w`, mode `pd`, folding into its sum/sumsq/cnt accumulators.
    // Each (w,pd) is scheduled at most once per wave, so the direct writes are race-free. The seed is a
    // pure function of (seed_base, r, w, pd) -- extending r for a later batch never reuses a draw.
    auto run_batch = [&](AIEngine& ai, int w, int pd, long long r0, long long r1)
    {
        const int H = work[w].H, idx = work[w].idx;
        const std::vector<int>& comp = tables[HAND - H].comps[idx];
        double sum = 0.0, sumsq = 0.0;
        std::vector<char> hit;                       // execution-trace scratch (per rollout), if tracing
        std::set<int>     cell_touched;              // union over this task's rollouts
        if (trace_on) { hit.assign(touch_names.size(), 0); }
        for (long long r = r0; r < r1; ++r)
        {
            // Fresh shuffle per rollout: pulling the top comp[b] cards of each bucket samples WHICH
            // specific members fill the slots (proportional to their deck counts). The library
            // continuation is then RE-SHUFFLED below (see the fix note) so its order is unbiased.
            const uint64_t rs = cfg.seed + 21'000'000ULL
                              + 0x9E3779B97F4A7C15ULL * (static_cast<uint64_t>(r) + 1)
                              + 1000003ULL * static_cast<uint64_t>(w) + static_cast<uint64_t>(pd);
            GameState s = GoldFishRunner::SetupGame(deck, rs);
            s.m_required_pieces = &rollout_profile.required_pieces;
            s.vial_target_mv    = rollout_profile.vial_target_mv;
            s.on_the_play       = (pd == 1);
            Player& ap = s.ActivePlayer();
            ap.hand.clear();
            for (int b = 0; b < K; ++b)
            {
                int need = comp[b];
                for (std::size_t k = 0; k < ap.library.size() && need > 0; )
                {
                    auto bit = bof.find(ap.library[k].m_name.str());
                    if (bit != bof.end() && bit->second == b)
                    { ap.hand.push_back(ap.library[k]); ap.library.erase(ap.library.begin() + k); --need; }
                    else { ++k; }
                }
            }
            // FIX (library-continuation bias): the top-pull above removes the EARLIEST copies of the
            // hand's card types, leaving the remaining library's top depleted of those types and
            // enriched in everything else -- notably LANDS. That made a spell-heavy / land-light hand
            // draw into its lands far too fast (measured: P(2 lands in first 2 draws) 0.29 vs the true
            // 0.20), inflating win-turn and spuriously KEEPING land-light hands. Re-shuffle the leftover
            // so the continuation is a fresh uniform permutation of the remaining cards; the hand's
            // member sampling from the top is already correct, only the ORDER was biased. Deterministic
            // + portable (SaltSeed), so pooling parity holds; a fixed salt keeps it independent of the
            // opening shuffle.
            ap.library.Shuffle(SaltSeed(rs, 0x5EED5ULL));
            double wt;
            if (trace_on)
            {
                std::fill(hit.begin(), hit.end(), 0);
                wt = ai.RolloutKeepWinTurn(s, 0, cfg.max_turns, &hit);
                for (std::size_t k = 0; k < hit.size(); ++k) { if (hit[k]) { cell_touched.insert(static_cast<int>(k)); } }
            }
            else { wt = ai.RolloutKeepWinTurn(s, 0, cfg.max_turns); }
            sum += wt; sumsq += wt * wt;
        }
        SizeTable& t = tables[HAND - H];
        t.sum[idx][pd]   += sum;
        t.sumsq[idx][pd] += sumsq;
        if (trace_on) { t.touched[idx][pd].insert(cell_touched.begin(), cell_touched.end()); }
        t.cnt[idx][pd]   += (r1 - r0);
    };

    // Single rollout r of cell w, mode pd -> win-turn (does NOT commit; the continuous path stores the
    // result in a per-(cell,r) slot and folds it deterministically). Same seed stream as run_batch
    // (pure function of seed_base,r,w,pd), so a cell's value is byte-identical to the wave path for the
    // same rollout set. Trace is unsupported on this path (a diagnostic; off by default).
    auto run_one = [&](AIEngine& ai, int w, int pd, long long r) -> double
    {
        const int H = work[w].H, idx = work[w].idx;
        const std::vector<int>& comp = tables[HAND - H].comps[idx];
        const uint64_t rs = cfg.seed + 21'000'000ULL
                          + 0x9E3779B97F4A7C15ULL * (static_cast<uint64_t>(r) + 1)
                          + 1000003ULL * static_cast<uint64_t>(w) + static_cast<uint64_t>(pd);
        GameState s = GoldFishRunner::SetupGame(deck, rs);
        s.m_required_pieces = &rollout_profile.required_pieces;
        s.vial_target_mv    = rollout_profile.vial_target_mv;
        s.on_the_play       = (pd == 1);
        Player& ap = s.ActivePlayer();
        ap.hand.clear();
        for (int b = 0; b < K; ++b)
        {
            int need = comp[b];
            for (std::size_t k = 0; k < ap.library.size() && need > 0; )
            {
                auto bit = bof.find(ap.library[k].m_name.str());
                if (bit != bof.end() && bit->second == b)
                { ap.hand.push_back(ap.library[k]); ap.library.erase(ap.library.begin() + k); --need; }
                else { ++k; }
            }
        }
        ap.library.Shuffle(SaltSeed(rs, 0x5EED5ULL));
        return ai.RolloutKeepWinTurn(s, 0, cfg.max_turns);
    };

    const int nthreads = std::max(1, std::min(concurrency_util::AffinityCpuCount(),
                                              static_cast<int>(work.size())));
    // Progress logging to STDERR (never stdout -> never corrupts the report; never affects rollouts,
    // V/counts or the written profile, so results stay deterministic). Generation is expensive, so each
    // phase/wave reports its size, a periodic %-done heartbeat, elapsed and the rollout rate. The clock is
    // wall-time only (diagnostic); it is not folded into any result.
    const auto t_gen = std::chrono::steady_clock::now();
    auto gen_elapsed = [&]() -> double
    { return std::chrono::duration<double>(std::chrono::steady_clock::now() - t_gen).count(); };
    long long rollouts_done = 0;   // cumulative across all passes, for a running rate
    // Run a wave of (w,pd,r0,r1) rollout tasks in parallel; each worker owns one AIEngine.
    struct Task { int w; int pd; long long r0; long long r1; };
    auto process_tasks = [&](const std::vector<Task>& tasks, const char* label)
    {
        if (tasks.empty()) { return; }
        long long batch_rollouts = 0;
        for (const Task& t : tasks) { batch_rollouts += (t.r1 - t.r0); }
        std::cerr << "[keepgen] " << label << ": " << tasks.size() << " tasks / " << batch_rollouts
                  << " rollouts on " << std::min(nthreads, static_cast<int>(tasks.size())) << " threads  ("
                  << static_cast<long long>(gen_elapsed()) << "s elapsed)\n" << std::flush;
        std::atomic<std::size_t> tc{0};
        const std::size_t step = std::max<std::size_t>(1, tasks.size() / 10);   // ~10% heartbeat
        std::atomic<std::size_t> next_report{ step };
        std::atomic<long long>   next_time{ 30 };      // ...OR every 30s, whichever comes first
        std::atomic<long long>   roll_done{ 0 };       // rollouts completed this phase (for a live rate)
        const auto t_batch = std::chrono::steady_clock::now();
        auto th_worker = [&]()
        {
            AIEngine ai(rollout_profile, cfg.depth, cfg.budget_ms);
            ai.SetSearchPostCombat(second_main);
            if (trace_on) { ai.SetTouchIndex(&touch_index); }   // execution-trace: record cards per rollout
            for (;;)
            {
                std::size_t k = tc.fetch_add(1);
                if (k >= tasks.size()) { break; }
                const Task& t = tasks[k];
                run_batch(ai, t.w, t.pd, t.r0, t.r1);
                const std::size_t done = k + 1;
                const long long   rd   = roll_done.fetch_add(t.r1 - t.r0) + (t.r1 - t.r0);
                const double el = std::chrono::duration<double>(
                                      std::chrono::steady_clock::now() - t_batch).count();
                bool report = false;
                std::size_t nr = next_report.load(std::memory_order_relaxed);
                if (done >= nr && next_report.compare_exchange_strong(nr, nr + step)) { report = true; }
                long long nt = next_time.load(std::memory_order_relaxed);
                if (!report && static_cast<long long>(el) >= nt
                    && next_time.compare_exchange_strong(nt, nt + 30)) { report = true; }
                if (report)
                {
                    std::cerr << "[keepgen]   " << label << " " << (100 * done / tasks.size()) << "%  ("
                              << done << "/" << tasks.size() << " tasks, " << rd << " rollouts, "
                              << static_cast<long long>(el > 0 ? rd / el : 0) << "/s, "
                              << static_cast<long long>(el) << "s phase / " << static_cast<long long>(gen_elapsed())
                              << "s total)\n" << std::flush;
                }
            }
        };
        std::vector<std::thread> pool;
        const int nt = std::max(1, std::min(nthreads, static_cast<int>(tasks.size())));
        for (int t = 0; t < nt; ++t) { pool.emplace_back(th_worker); }
        for (std::thread& th : pool) { th.join(); }
        rollouts_done += batch_rollouts;
        const double el = std::chrono::duration<double>(std::chrono::steady_clock::now() - t_batch).count();
        std::cerr << "[keepgen] " << label << " done: " << batch_rollouts << " rollouts in "
                  << static_cast<long long>(el) << "s (" << static_cast<long long>(el > 0 ? batch_rollouts / el : 0)
                  << "/s); cumulative " << rollouts_done << " rollouts, " << static_cast<long long>(gen_elapsed())
                  << "s total\n" << std::flush;
    };
    // Recompute V (mean) and se (stderr of the mean) for every cell from its accumulators.
    auto recompute = [&]()
    {
        for (int H = HAND; H >= min_size; --H)
        {
            SizeTable& t = tables[HAND - H];
            for (std::size_t i = 0; i < t.comps.size(); ++i)
                for (int pd = 0; pd < 2; ++pd)
                {
                    const long long c = t.cnt[i][pd];
                    if (c <= 0) { continue; }
                    const double mean = t.sum[i][pd] / c;
                    const double var  = c > 1 ? std::max(0.0, t.sumsq[i][pd] / c - mean * mean) : 0.0;
                    t.V[i][pd]  = mean;
                    t.se[i][pd] = c > 1 ? std::sqrt(var / c) : 0.0;
                }
        }
    };

    // Hypergeometric hand weights P and the keep/bottoming machinery (shared by the adaptive refine loop
    // below and the reporting in Sections 4-5). keep_val = best (HAND-m)-subcomposition value; argmin_sub
    // = the index of that best subcomposition in tables[m] (the cell whose noise drives the decision).
    const long long denom = Comb(static_cast<int>(deck.mainboard.size()), HAND);
    const SizeTable& H7 = tables[0];
    std::vector<double> P(H7.comps.size());
    for (std::size_t i = 0; i < H7.comps.size(); ++i)
    {
        long long num = 1;
        for (int b = 0; b < K; ++b) { num *= Comb(count[b], H7.comps[i][b]); }
        P[i] = static_cast<double>(num) / static_cast<double>(denom);
    }
    auto keep_val = [&](const std::vector<int>& h, int m, int pd) -> double
    {
        const int target = HAND - m;
        std::vector<std::vector<int>> subs;
        std::vector<int> cur(K, 0);
        EnumComps(0, target, cur, h, subs);   // subcompositions bounded by the hand
        double best = 1e9;
        const SizeTable& t = tables[HAND - target];
        for (const std::vector<int>& s : subs)
        {
            auto it = t.index.find(s);
            if (it != t.index.end()) { best = std::min(best, t.V[it->second][pd]); }
        }
        return best;
    };
    // The (7-m)-subcomposition that ATTAINS keep_val(h,m,pd) -- i.e. the argmin cell in tables[m]. Its
    // noise is what drives hand h's mull-m keep decision (and its bottoming). Returns -1 if none.
    auto argmin_sub = [&](const std::vector<int>& h, int m, int pd) -> int
    {
        const int target = HAND - m;
        std::vector<std::vector<int>> subs;
        std::vector<int> cur(K, 0);
        EnumComps(0, target, cur, h, subs);
        double best = 1e9; int arg = -1;
        const SizeTable& t = tables[HAND - target];   // == tables[m]
        for (const std::vector<int>& s : subs)
        {
            auto it = t.index.find(s);
            if (it != t.index.end() && t.V[it->second][pd] < best) { best = t.V[it->second][pd]; arg = it->second; }
        }
        return arg;
    };
    // Shrunk stderr of the mean for the STOP gate: pull the cell's sample variance toward the table's
    // pooled variance `vg` with se_prior pseudo-observations, so a low-R cell's spuriously-small sample
    // variance can't fake confidence (see MTG_KEEP_SE_PRIOR).
    auto gate_se = [&](const SizeTable& t, int i, int pd, double vg) -> double
    {
        const long long c = t.cnt[i][pd];
        if (c < 1) { return 0.0; }
        const double mean = t.V[i][pd];
        const double vc   = c > 1 ? std::max(0.0, t.sumsq[i][pd] / c - mean * mean) : vg;
        const double vs   = (c * vc + cfg.se_prior * vg) / (c + cfg.se_prior);
        return std::sqrt(vs / c);
    };
    auto compute_Dopt = [&](int pd) -> std::vector<double>
    {
        const int M = cfg.max_mull;
        std::vector<double> Dopt(M + 1, 0.0);
        for (std::size_t i = 0; i < H7.comps.size(); ++i) { Dopt[M] += P[i] * keep_val(H7.comps[i], M, pd); }
        for (int m = M - 1; m >= 0; --m)
            for (std::size_t i = 0; i < H7.comps.size(); ++i)
            { Dopt[m] += P[i] * std::min(keep_val(H7.comps[i], m, pd), Dopt[m + 1]); }
        return Dopt;
    };

    // Adaptive schedule (influence-driven). Sample EVERY cell to the floor r0, then in waves add
    // rollouts only to cells that could still change a keep decision or bias the threshold, until none
    // qualify or all hit the cap. r_floor<=0 or >=rollouts => uniform R (byte-identical to the old path).
    //
    // Two cell roles:
    //  * size-7 cell (mull-0): keep_val(h,0)=V[7][h], a plain mean. Refine while the mull-0 flip prob vs
    //    the threshold exceeds eps (a genuine near-tie); confident hands stay at the floor.
    //  * sub-cell (size 7-m, m>=1): sets keep_val(h,m)=min over subcomps. It is needed IFF it is the
    //    argmin for a hand that is NOT a confident mulligan -- i.e. a confident KEEP (its keep_val feeds
    //    the threshold, which must stay unbiased) or a near-tie (its own decision), or the terminal
    //    forced-keep level. Needed sub-cells go to the cap; sub-cells that are the argmin ONLY for
    //    confident-mulligan hands stay at the floor (their value enters every use through min(...,Dopt)
    //    on the mull branch, so it is never read). This is curse-SAFE by construction: the min-bias is
    //    downward, so an under-sampled cell reads LOWER -> looks MORE keepable -> gets classified needed
    //    and refined; it can never make a keep/near hand masquerade as a confident mulligan.
    const long long r_max = cfg.rollouts;
    const long long r0    = (cfg.r_floor > 0 && cfg.r_floor < cfg.rollouts) ? cfg.r_floor : r_max;
    const bool adaptive   = r0 < r_max;

    // ---- Periodic CHECKPOINT of the raw sidecar ------------------------------------------------
    // A long adaptive run (antilife floor pass alone is hours) writes its raw sidecar every
    // MTG_KEEP_CHECKPOINT_SEC (default 1800s; 0 disables) DURING the refine loop, so a crash/stop
    // after the floor pass loses only minutes. Each checkpoint is a COMPLETE-floor state (all cells
    // sampled >= r0) -> recover a profile from it with the merge path (MTG_KEEP_MERGE on this one
    // file). Written atomically (tmp + rename) so a crash mid-write can't corrupt the sidecar. This
    // is the same content as the final 6b write (below) minus the play_digest, which recovery on one
    // machine does not need. sumsq is included for a future resume-continuation path.
    const long long checkpoint_sec = []{ const char* s = std::getenv("MTG_KEEP_CHECKPOINT_SEC");
        return (s && *s) ? std::max<long long>(0, std::strtoll(s, nullptr, 10)) : 1800LL; }();
    // Floor-pass checkpoint granularity: the floor pass (Pass A) is split into this many task GROUPS,
    // with a (throttled) checkpoint written at each group barrier -- so a crash mid-floor loses at most
    // one group + one checkpoint interval, not the whole pass (the ~day-long full-pass was previously a
    // single all-or-nothing unit). Race-free (the barrier joins all workers before the atomic write).
    // A resumed run reloads the checkpoint and skips already-sampled cells (see RESUME below). Default
    // 32 (~1/32 of the floor per group); combined with MTG_KEEP_CHECKPOINT_SEC to bound write frequency.
    const long long floor_groups = []{ const char* s = std::getenv("MTG_KEEP_FLOOR_GROUPS");
        return (s && *s) ? std::max<long long>(1, std::strtoll(s, nullptr, 10)) : 32LL; }();
    // Continuous adaptive batched keep-gen (docs/design/adaptive-batched-keepgen.md): one persistent
    // pool over per-rollout tasks for the size-7 keep decision, freeze re-evaluated at periodic sweeps
    // instead of at wave barriers -> cores stay full to the last live cell. Default OFF -> the wave path
    // below is byte-identical. MTG_KEEP_CONTINUOUS_LOOKAHEAD bounds refine speculation past a cell's
    // committed prefix; MTG_KEEP_SWEEP_SEC throttles the (whole-table) Dopt/freeze sweep.
    const bool continuous = adaptive && std::getenv("MTG_KEEP_CONTINUOUS") != nullptr;
    const long long cont_lookahead = []{ const char* s = std::getenv("MTG_KEEP_CONTINUOUS_LOOKAHEAD");
        return (s && *s) ? std::max<long long>(1, std::strtoll(s, nullptr, 10)) : 4LL; }();
    const double sweep_sec = []{ const char* s = std::getenv("MTG_KEEP_SWEEP_SEC");
        return (s && *s) ? std::max(1.0, std::atof(s)) : 20.0; }();
    auto write_raw_atomic = [&](const std::string& path) -> bool
    {
        using json = nlohmann::json;
        uint64_t bucket_fp = 1469598103934665603ULL;
        for (int b = 0; b < K; ++b)
        { bucket_fp = Fnv("|", bucket_fp); for (const std::string& n : eq.classes[b].members) bucket_fp = Fnv(n + ",", bucket_fp); }
        std::vector<std::string> deck_names;
        for (const Card& c : deck.mainboard) { deck_names.push_back(c.m_name.str()); }
        std::sort(deck_names.begin(), deck_names.end());
        uint64_t deck_fp = 1469598103934665603ULL;
        for (const std::string& n : deck_names) { deck_fp = Fnv(n + ",", deck_fp); }
        json root;
        root["meta"] = {
            { "commit", cfg.commit }, { "play_digest", std::string() },
            { "bucket_fp", bucket_fp }, { "deck_fp", deck_fp },
            { "seed_base", cfg.seed }, { "R", cfg.rollouts }, { "max_mull", cfg.max_mull },
            { "probes", cfg.probes }, { "threshold", cfg.threshold }, { "K", K }, { "equiv_seed", cfg.equiv_seed }
        };
        json buckets = json::array();
        for (int b = 0; b < K; ++b) { buckets.push_back(eq.classes[b].members); }
        root["buckets"] = buckets;
        json sizes = json::array();
        for (int H = HAND; H >= min_size; --H)
        {
            const SizeTable& t = tables[HAND - H];
            json entries = json::array();
            for (std::size_t i = 0; i < t.comps.size(); ++i)
            {
                json je;
                je["comp"]  = t.comps[i];
                je["sum"]   = { t.sum[i][0], t.sum[i][1] };
                je["sumsq"] = { t.sumsq[i][0], t.sumsq[i][1] };
                je["count"] = { t.cnt[i][0], t.cnt[i][1] };
                entries.push_back(je);
            }
            sizes.push_back({ { "H", H }, { "entries", entries } });
        }
        root["sizes"] = sizes;
        const std::string tmp = path + ".tmp";
        { std::ofstream f(tmp); if (!f) { return false; } f << root.dump(); if (!f) { return false; } }
        std::error_code ec; std::filesystem::rename(tmp, path, ec);
        return !ec;
    };
    auto t_last_ck = std::chrono::steady_clock::now();
    auto maybe_checkpoint = [&]()
    {
        if (checkpoint_sec <= 0 || cfg.out_raw.empty()) { return; }
        const auto now = std::chrono::steady_clock::now();
        if (std::chrono::duration<double>(now - t_last_ck).count() < static_cast<double>(checkpoint_sec)) { return; }
        t_last_ck = now;
        const bool ok = write_raw_atomic(cfg.out_raw);
        std::cerr << "[keepgen] checkpoint " << (ok ? "written" : "FAILED") << " -> " << cfg.out_raw
                  << "  (" << static_cast<long long>(gen_elapsed()) << "s)\n" << std::flush;
    };

    // ---- RESUME-CONTINUATION of an interrupted floor pass (crash safety) ------------------------
    // If cfg.out_raw already EXISTS, a prior invocation of THIS same round wrote a floor checkpoint
    // before being killed. Reload its per-cell sum/sumsq/count into the accumulators so Pass A skips
    // cells already sampled to their floor -- turning a killed floor pass from "restart from scratch"
    // into "continue from the last checkpoint". Correctness: seeds are a pure function of
    // (seed_base,r,w,pd) and the accumulators use += only, so a reloaded cell holds byte-identical
    // samples to an uninterrupted run and the remaining cells draw the identical rollouts -> the
    // completed profile is byte-identical whether or not the run was interrupted. Fingerprints
    // (bucket/deck/seed/K/max_mull/R) MUST match, else the partial indexes a different table -> ignore
    // it and start fresh (loud warning; never mis-apply). Disjoint from PRIOR_RAW change-detection
    // (that loads pri_V for a DIFFERENT commit; this reloads live accumulators for the SAME run).
    long long resume_loaded = 0;
    if (!cfg.out_raw.empty() && std::filesystem::exists(cfg.out_raw))
    {
        std::ifstream rf(cfg.out_raw);
        nlohmann::json rj; bool ok_parse = true;
        try { rf >> rj; } catch (...) { ok_parse = false; }
        if (ok_parse && rj.contains("meta") && rj.contains("sizes"))
        {
            uint64_t r_bucket_fp = 1469598103934665603ULL;
            for (int b = 0; b < K; ++b)
            { r_bucket_fp = Fnv("|", r_bucket_fp);
              for (const std::string& n : eq.classes[b].members) { r_bucket_fp = Fnv(n + ",", r_bucket_fp); } }
            std::vector<std::string> rdn;
            for (const Card& c : deck.mainboard) { rdn.push_back(c.m_name.str()); }
            std::sort(rdn.begin(), rdn.end());
            uint64_t r_deck_fp = 1469598103934665603ULL;
            for (const std::string& n : rdn) { r_deck_fp = Fnv(n + ",", r_deck_fp); }
            const auto& rm = rj["meta"];
            const bool match = rm.value("bucket_fp", 0ULL) == r_bucket_fp
                            && rm.value("deck_fp", 0ULL) == r_deck_fp
                            && rm.value("seed_base", ~0ULL) == cfg.seed
                            && rm.value("K", -1) == K
                            && rm.value("max_mull", -1) == cfg.max_mull
                            && rm.value("equiv_seed", 0ULL) == cfg.equiv_seed
                            && rm.value("R", -1LL) == static_cast<long long>(cfg.rollouts);
            if (match)
            {
                for (const auto& sz : rj["sizes"])
                {
                    const int H = sz.value("H", 0);
                    if (H > HAND || H < min_size) { continue; }
                    SizeTable& t = tables[HAND - H];
                    for (const auto& e : sz["entries"])
                    {
                        auto it = t.index.find(e["comp"].get<std::vector<int>>());
                        if (it == t.index.end()) { continue; }
                        const int i = it->second;
                        for (int pd = 0; pd < 2; ++pd)
                        {
                            const long long c = e["count"][pd].get<long long>();
                            if (c <= 0) { continue; }
                            t.sum[i][pd]   = e["sum"][pd].get<double>();
                            t.sumsq[i][pd] = e["sumsq"][pd].get<double>();
                            t.cnt[i][pd]   = c;
                            ++resume_loaded;
                        }
                    }
                }
                recompute();
                std::cerr << "[keepgen] RESUME: reloaded " << resume_loaded << " sampled cell-sides from the "
                             "floor checkpoint " << cfg.out_raw << " -> continuing (already-sampled cells skipped)\n"
                          << std::flush;
            }
            else
            {
                std::cerr << "[keepgen] RESUME: existing " << cfg.out_raw << " fingerprints MISMATCH -- "
                             "IGNORING it and starting fresh (it will be overwritten by the next checkpoint)\n"
                          << std::flush;
            }
        }
    }

    // Sub-tables may start at the floor for adaptive keep-only profiles. With bottoming enabled the argmin
    // (which subhand to keep) normally needs the WHOLE sub-table accurate -- a true-argmin cell noisily-
    // high at the floor would never be marked -- so bottoming forces sub-tables to the cap up front. The
    // adaptive_bottom EXPERIMENT relaxes that: sub-tables stay adaptive, and best_sub instead excludes
    // floor-R cells from the bottoming argmin (so curse-noise can't pick one). Size-7 always starts at floor.
    // change-detection also needs every sub-table sampled at the floor first (as the detection batch),
    // even with bottoming on -- moved sub-cells are then refined to the cap, unmoved reuse the prior.
    const bool sub_floor = (adaptive && (!cfg.bottoming_enabled || cfg.adaptive_bottom)) || change_detect;
    {   // Pass A: size-7 to the floor; sub-tables to the floor (keep-only) or straight to the cap.
        std::vector<Task> tasks;
        tasks.reserve(work.size() * 2);
        for (int w = 0; w < static_cast<int>(work.size()); ++w)
        {
            // Continuous mode owns the size-7 floor+refine (its own pool below); Pass A does sub-tables
            // only, so the sub-table V it produces is ready for the continuous sweep's Dopt.
            if (continuous && work[w].H == HAND) { continue; }
            const long long init = (work[w].H == HAND || sub_floor) ? r0 : r_max;
            const int Hw = work[w].H, iw = work[w].idx;
            for (int pd = 0; pd < 2; ++pd)
            {
                // skip mode: a carried (frozen) size-7 cell gets 0 rollouts -- V preloaded, no samples.
                // Live/other cells keep their w, so seeds are unperturbed.
                if (Hw == HAND && frozen7[iw][pd]) { continue; }
                if (Hw >= 1 && Hw < HAND && frozen_sub[Hw][iw][pd]) { continue; }   // Phase 2 sub-table skip
                // Whole-pool reuse (EXTEND-DEPTH / identical play_digest): a cell taken verbatim from the
                // prior needs NO fresh floor sample -- change-detection marks it `resolved` and
                // apply_prior_override sets its V from the prior R=40 value regardless. Skipping it spends
                // the floor pass ONLY on cells the prior lacks (the new deeper sizes), turning a full
                // re-sample of every reused cell (~94% of the work on a depth extend) into ~zero.
                if (reuse_all_cells && has_prior[HAND - Hw][iw][pd]) { continue; }
                long long cell_init = init;
                // verify mode: a carried confident-mull cell starts at a REDUCED floor so the run skips
                // most of its floor cost; the adaptive refiner still tops it up if it flipped to keepable
                // on the new deck/commit. Adaptive only -- a uniform run has no refiner, so sample in full.
                if (Hw == HAND && carry_lowfloor7[iw][pd] && adaptive)
                { cell_init = std::min(cell_init, carry_floor); }
                // RESUME: a cell already sampled to its floor in a reloaded checkpoint needs no re-run
                // (its accumulators are already correct; += would double-count). Guarded on resume_loaded
                // so a normal (non-resumed) run is byte-identical.
                if (resume_loaded > 0 && tables[HAND - Hw].cnt[iw][pd] >= cell_init) { continue; }
                tasks.push_back({ w, pd, 0, cell_init });
            }
        }
        // Split the floor pass into groups so we can checkpoint at barriers (race-free) -- a crash mid-
        // floor then loses at most one group + one checkpoint interval, not the whole ~day-long pass.
        // Splitting is result-invariant (each task is independent; seeds are per-(w,pd,r)), and the whole
        // scheme is inert unless a raw path + checkpointing are set -> the plain path stays byte-identical.
        const char* lbl = adaptive ? "floor-pass" : "full-pass";
        if (cfg.out_raw.empty() || checkpoint_sec <= 0 || tasks.size() <= 1)
        {
            process_tasks(tasks, lbl);
        }
        else
        {
            const std::size_t groups = std::min<std::size_t>(tasks.size(),
                                                             static_cast<std::size_t>(floor_groups));
            const std::size_t chunk  = (tasks.size() + groups - 1) / groups;
            for (std::size_t off = 0; off < tasks.size(); off += chunk)
            {
                const std::size_t end = std::min(tasks.size(), off + chunk);
                std::vector<Task> grp(tasks.begin() + static_cast<long>(off),
                                      tasks.begin() + static_cast<long>(end));
                process_tasks(grp, lbl);
                maybe_checkpoint();   // throttled by MTG_KEEP_CHECKPOINT_SEC; race-free (barrier above)
            }
        }
        recompute();
    }

    // ---- change-detection: classify moved vs unmoved from the floor batch, then reuse the prior -----
    // For every cell with a prior, compare this run's thin floor estimate V_f (n_f = r0) to the prior V_p.
    // "Unmoved" IFF even the CI upper bound on the shift stays below the decision-relevant delta:
    //   |V_f - V_p| + detect_z * sqrt(var_f/n_f + var_p/n_p) < detect_delta.
    // Everything else is "moved" -> refined fresh (bias toward moved => misses are rare). Unmoved cells
    // reuse the prior's higher-R value for the policy (apply_prior_override) but keep their fresh floor
    // samples in the accumulators (valid new-commit samples -> the raw stays poolable). apply_prior_
    // override must run after EVERY recompute() (recompute derives V from the fresh accumulators, which
    // would otherwise clobber the prior value on resolved cells).
    auto apply_prior_override = [&]()
    {
        if (!change_detect) { return; }
        for (int H = HAND; H >= min_size; --H)
        {
            SizeTable& t = tables[HAND - H];
            for (std::size_t i = 0; i < t.comps.size(); ++i)
                for (int pd = 0; pd < 2; ++pd)
                    if (resolved[HAND - H][i][pd]) { t.V[i][pd] = pri_V[HAND - H][i][pd]; }
        }
    };
    if (change_detect)
    {
        // Effective delta = DISTANCE TO THRESHOLD, not a flat tolerance. We don't care whether a cell
        // moved; only whether it moved enough to flip its DECISION. A size-7 cell's m=0 keep decision
        // flips only if its value crosses Dopt[1], so a move smaller than |V - Dopt[1]| is
        // decision-irrelevant -- deep cells (huge margin) clear trivially from the thin floor batch,
        // near-threshold cells (tiny margin) can't clear and are refined (correctly). Certify unmoved iff
        // even the CI upper bound on the shift stays inside the margin: shift + z*se < margin. A deep
        // cell that moved ACROSS the threshold has shift > margin -> flagged moved -> refined (caught).
        // Sub-cells feed Dopt[1..M] thresholds AND the bottoming argmin, so a clean per-cell margin is
        // not well-defined -- they use the flat MTG_KEEP_DETECT_DELTA (conservative -> refine more; the
        // R-hungry bottoming carry is future work). Dopt from the fresh floor batch (its noise is small
        // -- an average over cells -- and deep-cell margins dwarf it).
        const std::array<std::vector<double>, 2> Dopt_det = { compute_Dopt(0), compute_Dopt(1) };
        long long n_unmoved = 0, n_moved = 0, n_tested = 0;
        for (int H = HAND; H >= min_size; --H)
        {
            SizeTable& t = tables[HAND - H];
            for (std::size_t i = 0; i < t.comps.size(); ++i)
                for (int pd = 0; pd < 2; ++pd)
                {
                    if (!has_prior[HAND - H][i][pd]) { continue; }   // no prior -> treat as moved (refine)
                    // Execution-trace: prior touched-set disjoint from the changed cards => this cell's
                    // rollouts are byte-identical on the new commit => reuse the prior EXACTLY (no
                    // statistical test, covers near-threshold + bottoming cells). Composes with the
                    // statistical detection below for cells that DID touch a changed card.
                    if (!trace_reuse[HAND - H].empty() && trace_reuse[HAND - H][i])
                    { resolved[HAND - H][i][pd] = true; continue; }
                    const long long nf = t.cnt[i][pd];
                    if (nf < 1) { continue; }
                    ++n_tested;
                    const double Vf   = t.V[i][pd];
                    const double Vp   = pri_V[HAND - H][i][pd];
                    const double varf = (nf > 1) ? std::max(0.0, t.sumsq[i][pd] / nf - Vf * Vf)
                                                 : pri_var[HAND - H][i][pd];
                    const double np   = static_cast<double>(pri_n[HAND - H][i][pd]);
                    const double se   = std::sqrt(varf / nf + pri_var[HAND - H][i][pd] / np);
                    const double shift = std::abs(Vf - Vp);
                    // margin: size-7 -> distance from the prior value to the m=0 threshold; sub-cells ->
                    // flat delta.
                    const double margin = (H == HAND) ? std::abs(Vp - Dopt_det[pd][1]) : detect_delta;
                    if (shift + detect_z * se < margin)
                    { resolved[HAND - H][i][pd] = true; ++n_unmoved; }
                    else { ++n_moved; }
                }
        }
        apply_prior_override();
        os << "change-detection: " << n_tested << " prior cell-sides tested -> " << n_unmoved
           << " unmoved (reuse prior), " << n_moved << " moved (refine fresh)  [size-7 margin=dist-to-thr, "
           << "sub delta=" << detect_delta << ", z=" << detect_z << "]\n";
        std::cerr << "[keepgen] change-detection: " << n_unmoved << " unmoved / " << n_moved
                  << " moved (of " << n_tested << " prior cell-sides)\n" << std::flush;
    }

    // Refine waves, shared by the continuous size-7 pool (sub_only=true, run FIRST to fix Dopt) and the
    // non-continuous full path (sub_only=false). sub_only skips the m=0 size-7 gate so only sub-cells are
    // refined. Dopt is one-directional off the sub-tables (compute_Dopt never reads size-7 V), so
    // converging the sub-tables in isolation yields the SAME Dopt the full wave path converges to -> the
    // continuous size-7 freeze can then gate against an exact, fixed threshold.
    int refine_waves = 0;
    long long refined_rollouts = 0;
    auto run_refine_waves = [&](bool sub_only)
    {
        const double SQRT2 = 1.4142135623730951;
        for (;;)
        {
            const std::array<std::vector<double>, 2> Dopt = { compute_Dopt(0), compute_Dopt(1) };
            // Pooled win-turn variance per table per pd -- the shrink target for the stop gate (variance
            // scales with hand size, so it is per-table). Recomputed each wave; cheap vs the rollouts.
            std::vector<std::array<double, 2>> vg(tables.size(), { 0.0, 0.0 });
            for (int H = HAND; H >= min_size; --H)
            {
                const SizeTable& t = tables[HAND - H]; std::array<long long, 2> ng = { 0, 0 };
                for (std::size_t i = 0; i < t.comps.size(); ++i)
                    for (int pd = 0; pd < 2; ++pd)
                    { const long long c = t.cnt[i][pd];
                      if (c > 1) { const double mn = t.V[i][pd];
                                   vg[HAND - H][pd] += std::max(0.0, t.sumsq[i][pd] / c - mn * mn); ++ng[pd]; } }
                for (int pd = 0; pd < 2; ++pd) { if (ng[pd] > 0) { vg[HAND - H][pd] /= ng[pd]; } }
            }
            // Mark cells to top up this wave, keyed (tableIdx = HAND-H, cellIdx, pd) so a sub-cell that is
            // the argmin for several hands is marked once.
            std::set<std::array<int, 3>> mark;
            for (int pd = 0; pd < 2; ++pd)
                for (std::size_t i = 0; i < H7.comps.size(); ++i)
                {
                    // m=0: size-7 flip gate. Skipped in sub_only mode (the continuous pool owns size-7).
                    // Pruned (frozen) or change-detection-RESOLVED cells are never refined.
                    if (!sub_only && !frozen7[i][pd] && !resolved[0][i][pd] && H7.cnt[i][pd] < r_max)
                    {
                        const double se = gate_se(H7, static_cast<int>(i), pd, vg[0][pd]);
                        const double d  = std::abs(H7.V[i][pd] - Dopt[pd][1]);
                        const double flip = (se > 0) ? 0.5 * std::erfc(d / (se * SQRT2)) : (d == 0 ? 0.5 : 0.0);
                        if (flip > cfg.flip_eps) { mark.insert({ 0, static_cast<int>(i), pd }); }
                    }
                    // m>=1: the argmin sub-cell is needed unless h is a confident mulligan at m.
                    for (int m = 1; m <= cfg.max_mull; ++m)
                    {
                        const int arg = argmin_sub(H7.comps[i], m, pd);
                        if (arg < 0) { continue; }
                        if (resolved[m][arg][pd]) { continue; }       // change-detection: unmoved -> prior
                        const SizeTable& t = tables[m];               // size-(7-m) table
                        if (t.cnt[arg][pd] >= r_max) { continue; }
                        if (m == cfg.max_mull) { mark.insert({ m, arg, pd }); continue; }   // terminal: always
                        // With bottoming enabled the sub-table also serves the argmin (which subhand to
                        // keep), which needs the full sub-table accurate -- so skip the confident-mull
                        // shortcut and drive every sub-cell to the cap. Keep-only (bottoming off) profiles
                        // may skip confident-mulligan sub-cells (their value is never read via min).
                        const double kv  = t.V[arg][pd];              // = keep_val(h,m)
                        const double thr = Dopt[pd][m + 1];
                        const double se  = gate_se(t, arg, pd, vg[m][pd]);
                        const double flip = (se > 0) ? 0.5 * std::erfc(std::abs(kv - thr) / (se * SQRT2))
                                                     : (kv == thr ? 0.5 : 0.0);
                        const bool confident_mull = (!cfg.bottoming_enabled || cfg.adaptive_bottom)
                                                  && (kv - thr > 0.0) && (flip <= cfg.flip_eps);
                        if (!confident_mull) { mark.insert({ m, arg, pd }); }
                    }
                }
            if (mark.empty()) { break; }
            std::vector<Task> tasks;
            tasks.reserve(mark.size());
            for (const std::array<int, 3>& mk : mark)
            {
                const int H_idx = mk[0], arg = mk[1], pd = mk[2];
                const long long c   = tables[H_idx].cnt[arg][pd];
                const long long add = std::min<long long>(cfg.r_batch, r_max - c);
                if (add <= 0) { continue; }
                tasks.push_back({ work_idx[H_idx][arg], pd, c, c + add });
                refined_rollouts += add;
            }
            if (tasks.empty()) { break; }
            const std::string wlabel = std::string(sub_only ? "sub-refine-wave-" : "refine-wave-")
                                     + std::to_string(refine_waves + 1);
            process_tasks(tasks, wlabel.c_str());
            recompute();
            apply_prior_override();   // recompute derives V from fresh accumulators -> restore prior on resolved
            ++refine_waves;
            maybe_checkpoint();   // crash-safe: dump the raw sidecar every checkpoint_sec (post-floor)
        }
    };

    // ================= CONTINUOUS ADAPTIVE POOL (size-7 floor + refine in one batched queue) =========
    // docs/design/adaptive-batched-keepgen.md. One persistent worker pool over per-rollout tasks; each
    // rollout lands in its own slot and folds into the cell's sum in fixed r-order (deterministic value).
    // DETERMINISM (no slowest-cell throttle): the floor pass fills every cell to r0, then Dopt/vg are
    // FIXED from that complete floor snapshot; thereafter each cell freezes INDEPENDENTLY the first level
    // its own confidence crosses (flip<=flip_eps / low-prob), evaluated inside the fold on the fixed
    // refs. A cell's freeze level is a pure function of its own rollouts + the fixed refs, so two runs are
    // byte-identical regardless of scheduling timing, and no cell waits on any other -> cores stay full
    // to the last live cell. Sub-tables are already at their final values before Dopt is fixed: capped by
    // Pass A (bottoming-on) or converged by run_refine_waves(sub_only) just below (sub_floor cases).
    if (continuous)
    {
        // Converge sub-tables first so Dopt_ref (fixed after the size-7 floor below) is exact. Dopt is
        // one-directional (reads only sub-tables), so this needs no size-7 samples. sub_floor is false for
        // bottoming-on decks (Pass A already capped the sub-tables) -> skipped, and the validated
        // size-7-only path stays byte-identical. Barrier-bound, but sub-tables are small vs size-7.
        if (sub_floor) { run_refine_waves(true); }
        const double SQRT2 = 1.4142135623730951;
        SizeTable& S7 = tables[0];
        const int NC  = static_cast<int>(S7.comps.size());
        const double    cutoff_P = []{ const char* s = std::getenv("MTG_KEEP_CUTOFF_P");
            return (s && *s) ? std::atof(s) : 0.0; }();
        const long long cutoff_R = []{ const char* s = std::getenv("MTG_KEEP_CUTOFF_R");
            return (s && *s) ? std::atoll(s) : 0LL; }();
        const double se_prior = cfg.se_prior, flip_eps = cfg.flip_eps;

        const std::size_t SL = static_cast<std::size_t>(NC) * 2 * static_cast<std::size_t>(r_max);
        std::vector<double> slot(SL, 0.0);
        std::vector<char>   have(SL, 0);
        std::vector<long long> fed(static_cast<std::size_t>(NC) * 2, 0);
        std::vector<std::atomic<char>> afroze(static_cast<std::size_t>(NC) * 2);   // lock-free view for producer
        for (int i = 0; i < NC; ++i) for (int pd = 0; pd < 2; ++pd)
        { const std::size_t k = static_cast<std::size_t>(i) * 2 + pd;
          fed[k] = S7.cnt[i][pd];                                    // resume: continue past reloaded cnt
          afroze[k].store(frozen7[i][pd] ? 1 : 0, std::memory_order_relaxed); }
        auto SLOT = [&](int i, int pd, long long r) -> std::size_t
        { return ((static_cast<std::size_t>(i) * 2 + pd) * static_cast<std::size_t>(r_max)) + static_cast<std::size_t>(r); };

        std::mutex fold_mtx;                         // guards the fold (sum/sumsq/cnt + slot/have + frozen7)
        std::mutex qmtx; std::condition_variable q_ne, q_nf;
        std::deque<std::array<long long, 3>> q;      // {i, pd, r}
        const std::size_t QCAP = static_cast<std::size_t>(8 * nthreads);
        std::atomic<long long> in_flight{ 0 };
        std::atomic<bool> producing{ true };
        std::atomic<bool> refs_ready{ false };       // false = floor phase (no freezing); true = refine phase
        std::mutex prod_mtx; std::condition_variable prod_cv;
        std::array<std::vector<double>, 2> Dopt_ref{ std::vector<double>{}, std::vector<double>{} };
        std::array<double, 2> vg_ref{ 0.0, 0.0 };

        // WORKER: run one rollout, then fold its cell's committed prefix in fixed r-order. Once refs are
        // ready, evaluate freeze AT EACH new level c (>=r0) inside the fold; freeze at the first confident
        // level and stop folding (cnt truncates there -> deterministic; any in-flight lookahead rollouts
        // for a frozen cell are left unfolded, capped at cont_lookahead of waste).
        auto worker = [&]()
        {
            AIEngine ai(rollout_profile, cfg.depth, cfg.budget_ms);
            ai.SetSearchPostCombat(second_main);
            for (;;)
            {
                std::array<long long, 3> task;
                {
                    std::unique_lock<std::mutex> lk(qmtx);
                    q_ne.wait(lk, [&]{ return !q.empty() || !producing.load(); });
                    if (q.empty()) { if (!producing.load()) { break; } else { continue; } }
                    task = q.front(); q.pop_front();
                }
                q_nf.notify_one();
                const int i = static_cast<int>(task[0]), pd = static_cast<int>(task[1]);
                const long long r = task[2];
                const double wt = run_one(ai, work_idx[0][i], pd, r);
                {
                    std::lock_guard<std::mutex> fk(fold_mtx);
                    slot[SLOT(i, pd, r)] = wt; have[SLOT(i, pd, r)] = 1;
                    long long& c = S7.cnt[i][pd];
                    const bool refine = refs_ready.load(std::memory_order_acquire);
                    while (!frozen7[i][pd] && c < r_max && have[SLOT(i, pd, c)])
                    {
                        const double v = slot[SLOT(i, pd, c)];
                        S7.sum[i][pd] += v; S7.sumsq[i][pd] += v * v; ++c;
                        if (refine && c >= r0)
                        {
                            bool fr = (c >= r_max)
                                || (cutoff_P > 0.0 && cutoff_R > 0 && P[i] < cutoff_P && c >= cutoff_R);
                            if (!fr)
                            {
                                const double mean = S7.sum[i][pd] / c;
                                const double vc   = c > 1 ? std::max(0.0, S7.sumsq[i][pd] / c - mean * mean)
                                                          : vg_ref[pd];
                                const double vs   = (c * vc + se_prior * vg_ref[pd]) / (c + se_prior);
                                const double se   = std::sqrt(vs / c);
                                const double d    = std::abs(mean - Dopt_ref[pd][1]);
                                const double flip = (se > 0) ? 0.5 * std::erfc(d / (se * SQRT2)) : (d == 0 ? 0.5 : 0.0);
                                if (flip <= flip_eps) { fr = true; }
                            }
                            if (fr) { frozen7[i][pd] = true;
                                      afroze[static_cast<std::size_t>(i) * 2 + pd].store(1, std::memory_order_release); }
                        }
                    }
                }
                in_flight.fetch_sub(1);
                prod_cv.notify_one();
            }
        };

        // Fix Dopt/vg from the COMPLETE floor (every cell at >= r0). Called once, under fold_mtx.
        auto compute_refs = [&]()
        {
            std::lock_guard<std::mutex> fk(fold_mtx);
            for (int i = 0; i < NC; ++i) for (int pd = 0; pd < 2; ++pd)
            {
                const long long c = S7.cnt[i][pd]; if (c <= 0) { continue; }
                const double mean = S7.sum[i][pd] / c;
                const double var  = c > 1 ? std::max(0.0, S7.sumsq[i][pd] / c - mean * mean) : 0.0;
                S7.V[i][pd] = mean; S7.se[i][pd] = c > 1 ? std::sqrt(var / c) : 0.0;
            }
            std::array<double, 2> vg{ 0.0, 0.0 }; std::array<long long, 2> ng{ 0, 0 };
            for (int i = 0; i < NC; ++i) for (int pd = 0; pd < 2; ++pd)
            { const long long c = S7.cnt[i][pd];
              if (c > 1) { const double mn = S7.V[i][pd];
                           vg[pd] += std::max(0.0, S7.sumsq[i][pd] / c - mn * mn); ++ng[pd]; } }
            for (int pd = 0; pd < 2; ++pd) { if (ng[pd] > 0) { vg[pd] /= ng[pd]; } }
            vg_ref = vg;
            Dopt_ref = { compute_Dopt(0), compute_Dopt(1) };
        };
        auto checkpoint = [&]()
        { if (cfg.out_raw.empty()) { return; }
          std::lock_guard<std::mutex> fk(fold_mtx); write_raw_atomic(cfg.out_raw); };

        std::vector<std::thread> pool;
        const int nw = std::max(1, nthreads);
        for (int t = 0; t < nw; ++t) { pool.emplace_back(worker); }
        std::cerr << "[keepgen] continuous size-7: " << NC << " cells, floor R=" << r0 << " cap R=" << r_max
                  << ", lookahead=" << cont_lookahead << ", ckpt=" << sweep_sec << "s on " << nw
                  << " threads\n" << std::flush;

        auto t_last_ck = std::chrono::steady_clock::now();
        long long fed_total = 0, last_report = 0;
        for (;;)
        {
            const bool refine = refs_ready.load();
            bool any_below_floor = false, any_live = false, any_fed = false;
            for (int i = 0; i < NC; ++i) for (int pd = 0; pd < 2; ++pd)
            {
                if (afroze[static_cast<std::size_t>(i) * 2 + pd].load()) { continue; }
                const long long c = S7.cnt[i][pd];                          // racy read (x86-64 atomic); benign
                if (c >= r_max) { continue; }
                any_live = true;
                long long limit;
                if (!refine) { limit = r0; if (c < r0) { any_below_floor = true; } }   // floor: fill to r0 only
                else         { limit = std::min<long long>(r_max, c + cont_lookahead); }
                long long& f = fed[static_cast<std::size_t>(i) * 2 + pd];
                while (f < limit)
                {
                    { std::unique_lock<std::mutex> lk(qmtx);
                      q_nf.wait(lk, [&]{ return q.size() < QCAP; });
                      q.push_back({ static_cast<long long>(i), static_cast<long long>(pd), f }); }
                    q_ne.notify_one();
                    ++f; in_flight.fetch_add(1); ++fed_total; any_fed = true;
                }
            }
            // Floor complete (every cell folded to >= r0, nothing in flight) -> fix refs, enter refine.
            if (!refine && !any_below_floor && in_flight.load() == 0)
            {
                compute_refs();
                refs_ready.store(true, std::memory_order_release);
                std::cerr << "[keepgen]   continuous: floor complete, refs fixed -> refine ("
                          << static_cast<long long>(gen_elapsed()) << "s)\n" << std::flush;
                continue;
            }
            const auto now = std::chrono::steady_clock::now();
            if (std::chrono::duration<double>(now - t_last_ck).count() >= sweep_sec)
            { checkpoint(); t_last_ck = now; }
            if (fed_total - last_report >= 20000)
            { last_report = fed_total;
              std::cerr << "[keepgen]   continuous: " << fed_total << " rollouts fed, in_flight="
                        << in_flight.load() << (refine ? " (refine)" : " (floor)") << " ("
                        << static_cast<long long>(gen_elapsed()) << "s)\n" << std::flush; }
            if (refine && !any_live && in_flight.load() == 0) { break; }
            if (!any_fed)
            { std::unique_lock<std::mutex> pk(prod_mtx);
              prod_cv.wait_for(pk, std::chrono::milliseconds(100)); }
        }
        producing.store(false); q_ne.notify_all();
        for (std::thread& th : pool) { th.join(); }
        recompute();
        if (!cfg.out_raw.empty()) { write_raw_atomic(cfg.out_raw); }
        rollouts_done += fed_total;
        std::cerr << "[keepgen] continuous size-7 DONE: " << fed_total << " rollouts, "
                  << static_cast<long long>(gen_elapsed()) << "s total\n" << std::flush;
    }
    // ================================================================================================

    // Save the (expensive) floor investment immediately -- refine waves can be long, so don't wait for
    // the first wave boundary. A complete-floor sidecar is already a valid (low-R) recoverable state.
    if (adaptive && !continuous) { maybe_checkpoint(); }

    if (adaptive && !continuous) { run_refine_waves(false); }

    if (adaptive)
    {
        os << "adaptive sampling: floor R=" << r0 << " cap R=" << r_max << " (flip_eps=" << cfg.flip_eps
           << ", se_prior=" << cfg.se_prior << ", batch=" << cfg.r_batch << ") -> " << refine_waves
           << " waves, " << refined_rollouts << " extra rollouts\n";
        // Per-table realized R (both pd) vs the uniform cap -> the savings by hand size.
        long long uniform_total = 0, actual_total = 0;
        for (int H = HAND; H >= min_size; --H)
        {
            const SizeTable& t = tables[HAND - H];
            long long cmin = r_max, cmax = 0, csum = 0, ncell = 0;
            for (std::size_t i = 0; i < t.comps.size(); ++i)
                for (int pd = 0; pd < 2; ++pd)
                { long long c = t.cnt[i][pd]; cmin = std::min(cmin, c); cmax = std::max(cmax, c);
                  csum += c; ++ncell; }
            uniform_total += static_cast<long long>(t.comps.size()) * 2 * r_max;
            actual_total  += csum;
            os << "  size-" << H << ": R min=" << cmin << " max=" << cmax
               << " mean=" << (ncell ? static_cast<double>(csum) / ncell : 0.0)
               << "  (" << t.comps.size() << " cells)\n";
        }
        os << "  total rollouts " << actual_total << " vs uniform " << uniform_total << " = "
           << (uniform_total ? 100.0 * actual_total / uniform_total : 0.0) << "% ("
           << (uniform_total ? 100.0 * (1.0 - static_cast<double>(actual_total) / uniform_total) : 0.0)
           << "% saved)\n" << std::flush;
    }

    // ---- 4/5. Backward-induction mulligan value: optimal keep vs the static keep rule ------------
    // keep_val / P / denom / H7 were hoisted above (shared with the adaptive refine loop). Weights P
    // are the multivariate-hypergeometric P(draw this 7-card composition).
    AIEngine ref_ai(profile, cfg.depth, cfg.budget_ms);   // static keep rule (ReferenceKeep = KeepHand)
    auto hand_cards = [&](const std::vector<int>& h)
    {
        std::vector<Card> cards;
        for (int b = 0; b < K; ++b) { for (int c = 0; c < h[b]; ++c) { cards.push_back(rep[b]); } }
        return cards;
    };

    os << "\n--- policy value (expected win-turn; lower is better) ---\n";
    os << "pd      D_opt   D_static   gap      keep%%_opt  keep%%_static\n";
    double opt_avg = 0, stat_avg = 0;
    std::array<std::vector<double>, 2> Dopt_pd, Dst_pd;
    for (int pd = 0; pd < 2; ++pd)
    {
        const int M = cfg.max_mull;
        std::vector<double> Dopt(M + 1, 0.0), Dst(M + 1, 0.0);
        // Terminal (forced keep at the deepest mulligan): value = KeepVal, no mull option.
        for (std::size_t i = 0; i < H7.comps.size(); ++i)
        {
            double kv = keep_val(H7.comps[i], M, pd);
            Dopt[M] += P[i] * kv;
            Dst[M]  += P[i] * kv;
        }
        long long kept_opt = 0, kept_st = 0;
        for (int m = M - 1; m >= 0; --m)
        {
            for (std::size_t i = 0; i < H7.comps.size(); ++i)
            {
                double kv = keep_val(H7.comps[i], m, pd);
                Dopt[m] += P[i] * std::min(kv, Dopt[m + 1]);
                bool sk = ref_ai.ReferenceKeep(hand_cards(H7.comps[i]), m, pd == 1);
                Dst[m]  += P[i] * (sk ? kv : Dst[m + 1]);
                if (m == 0)
                {
                    if (kv <= Dopt[1]) { kept_opt++; }
                    if (sk)            { kept_st++;  }
                }
            }
        }
        // keep% at m=0 by hand-count (unweighted) for a quick read of aggressiveness.
        double kopt = 100.0 * static_cast<double>(kept_opt) / static_cast<double>(H7.comps.size());
        double kst  = 100.0 * static_cast<double>(kept_st)  / static_cast<double>(H7.comps.size());
        os << (pd == 1 ? "play  " : "draw  ")
           << "  " << Dopt[0] << "   " << Dst[0]
           << "   " << (Dst[0] - Dopt[0]) << "    " << kopt << "      " << kst << "\n";
        opt_avg += Dopt[0] / 2.0; stat_avg += Dst[0] / 2.0;
        Dopt_pd[pd] = std::move(Dopt); Dst_pd[pd] = std::move(Dst);
    }
    os << "avg     D_opt=" << opt_avg << "  D_static=" << stat_avg
       << "  gap=" << (stat_avg - opt_avg) << " turns (optimal keep decisions vs static)\n";

    // ---- 5b. Full disagreement set: every m=0 hand where optimal != static, ranked by the ------
    // win-turn cost it contributes (P(hand) * |V_keep - mull threshold|). The agreeing hands add 0,
    // so these rows EXACTLY decompose the D_static-D_opt gap. On the play (pd=1).
    auto fmt_hand = [&](const std::vector<int>& h)
    {
        std::string s; bool first = true;
        for (int b = 0; b < K; ++b)
        { if (h[b] > 0) { if (!first) { s += ", "; } first = false;
                          s += std::to_string(h[b]) + "x " + label[b]; } }
        return s;
    };
    struct Diff { std::vector<int> h; double P, kv, thr, weighted; bool opt_keep, st_keep; };
    std::vector<Diff> diffs;
    double mass = 0.0, gap = 0.0, mass_overkeep = 0.0, mass_overmull = 0.0;
    const std::vector<double>& Do = Dopt_pd[1];
    for (std::size_t i = 0; i < H7.comps.size(); ++i)
    {
        double kv = keep_val(H7.comps[i], 0, 1);
        bool ok = kv <= Do[1];
        bool sk = ref_ai.ReferenceKeep(hand_cards(H7.comps[i]), 0, true);
        if (ok == sk) { continue; }
        double regret = std::abs(kv - Do[1]);
        diffs.push_back({ H7.comps[i], P[i], kv, Do[1], P[i] * regret, ok, sk });
        mass += P[i]; gap += P[i] * regret;
        if (sk && !ok) { mass_overkeep += P[i]; } else { mass_overmull += P[i]; }
    }
    std::sort(diffs.begin(), diffs.end(),
              [](const Diff& a, const Diff& b){ return a.weighted > b.weighted; });
    os << "\n--- static vs optimal DISAGREEMENTS (on the play, mull 0) ---\n";
    os << diffs.size() << " hand-types disagree; total draw-prob " << (100.0 * mass)
       << "% ; win-turn cost " << gap << " (static over-keeps " << (100.0 * mass_overkeep)
       << "%, over-mulls " << (100.0 * mass_overmull) << "%)\n";
    os << "rank  P%      Vkeep  thr    static->opt   cost    cum%   hand\n";
    double cum = 0.0;
    for (std::size_t i = 0; i < diffs.size() && i < 25; ++i)
    {
        const Diff& d = diffs[i];
        cum += d.weighted;
        os << "  " << (i + 1) << "   " << (100.0 * d.P) << "   " << d.kv << "  " << d.thr
           << "   " << (d.st_keep ? "KEEP->MULL" : "MULL->KEEP")
           << "   " << d.weighted << "   " << (gap > 0 ? 100.0 * cum / gap : 0.0)
           << "   " << fmt_hand(d.h) << "\n";
    }

    // ---- 6. Decisions on notable marginal hands -------------------------------------------------
    auto decide = [&](const std::vector<std::string>& names)
    {
        std::vector<int> h(K, 0);
        bool ok = true;
        for (const std::string& nm : names)
        {
            auto it = bucket_of.find(nm);
            if (it == bucket_of.end()) { ok = false; break; }
            h[it->second]++;
        }
        if (!ok || (int)names.size() != HAND) { os << "  (skip: " << names.size() << " cards)\n"; return; }
        // recompute Dopt[1]/Dst[1] on the play for the threshold (pd=1).
        const int pd = 1, M = cfg.max_mull;
        std::vector<double> Dopt(M + 1, 0.0), Dst(M + 1, 0.0);
        for (std::size_t i = 0; i < H7.comps.size(); ++i)
        { double kv = keep_val(H7.comps[i], M, pd); Dopt[M] += P[i]*kv; Dst[M] += P[i]*kv; }
        for (int m = M - 1; m >= 0; --m)
            for (std::size_t i = 0; i < H7.comps.size(); ++i)
            { double kv = keep_val(H7.comps[i], m, pd);
              Dopt[m] += P[i]*std::min(kv, Dopt[m+1]);
              Dst[m]  += P[i]*(ref_ai.ReferenceKeep(hand_cards(H7.comps[i]), m, true) ? kv : Dst[m+1]); }
        double kv0 = keep_val(h, 0, pd);
        bool opt_keep = kv0 <= Dopt[1];
        bool st_keep  = ref_ai.ReferenceKeep(hand_cards(h), 0, true);
        os << "  optimal=" << (opt_keep ? "KEEP" : "MULL")
           << " (V=" << kv0 << " vs mull " << Dopt[1] << ")   static="
           << (st_keep ? "KEEP" : "MULL") << "   [";
        for (std::size_t i = 0; i < names.size(); ++i) { os << (i ? ", " : "") << names[i]; }
        os << "]\n";
    };
    // ---- 5c. Label-noise diagnostic: how much draw-probability mass sits within k*stderr of the ---
    // keep/mull threshold (where R's noise can flip the decision). Large mass here => need more R.
    {
        const double thr = Dopt_pd[1][1];   // on-the-play mull-0 threshold
        double se_mass = 0.0, amb1 = 0.0, amb2 = 0.0, noise_regret = 0.0; long long amb2n = 0;
        for (std::size_t i = 0; i < H7.comps.size(); ++i)
        {
            const double se = H7.se[i][1];
            const double v  = H7.V[i][1];    // KeepVal(h,0) = V[7][h] for m=0
            const double d  = std::abs(v - thr);
            se_mass += P[i] * se;
            if (se > 0 && d < se)       { amb1 += P[i]; }
            if (se > 0 && d < 2.0 * se) { amb2 += P[i]; ++amb2n; }
            // Expected win-turn lost to noise on this hand: probability the noisy estimate lands on
            // the wrong side of the threshold, times the cost of being wrong (= the true gap d).
            // Flips only happen where d is small, so each term -- and the total -- is marginal.
            const double flip = (se > 0) ? 0.5 * std::erfc(d / (se * 1.4142135623730951))
                                         : (d == 0 ? 0.5 : 0.0);
            noise_regret += P[i] * d * flip;
        }
        os << "\n--- label noise (R=" << cfg.rollouts << ", on the play, mull 0) ---\n";
        os << "prob-weighted per-hand stderr = " << se_mass << " turns\n";
        os << "draw-prob mass within 1 stderr of threshold = " << (100.0 * amb1)
           << "% ; within 2 stderr = " << (100.0 * amb2) << "% (" << amb2n << " hand-types)\n";
        os << "EST. win-turn lost to label noise ~= " << noise_regret
           << " (flips only near-ties -> shortfall stays marginal; raise R to shrink)\n";
        // Project the noise-regret at other R from this run's per-hand variance (stderr ~ 1/sqrt(R)).
        // Shows how low R can go before the policy degrades -- the lever for higher-combination decks.
        os << "projected regret vs R (extrapolated): ";
        for (int Rt : { 5, 10, 20, 50, 100, 200, 500 })
        {
            double reg = 0.0;
            for (std::size_t i = 0; i < H7.comps.size(); ++i)
            {
                const double seR = H7.se[i][1] * std::sqrt(static_cast<double>(cfg.rollouts) / Rt);
                const double d   = std::abs(H7.V[i][1] - thr);
                const double flip = (seR > 0) ? 0.5 * std::erfc(d / (seR * 1.4142135623730951))
                                              : (d == 0 ? 0.5 : 0.0);
                reg += P[i] * d * flip;
            }
            os << "R=" << Rt << ":~" << reg << "  ";
        }
        os << "\n";
    }

    // (play_digest is computed earlier -- the change-detection carry needs it -- and reused here.)

    // ---- 6. Serialize the keep policy (bucket map + per-composition keep decisions) --------------
    // Built via the shared BuildPolicyFromTables so the in-run policy is byte-identical to what the
    // offline merge tool (RunKeepMerge) produces from the same pooled V's.
    if (!cfg.out_profile.empty())
    {
        std::vector<std::vector<std::string>> bmembers;
        for (int b = 0; b < K; ++b) { bmembers.push_back(eq.classes[b].members); }
        ExhaustiveKeepPolicy ek = BuildPolicyFromTables(
            tables, count, bmembers, static_cast<int>(deck.mainboard.size()),
            cfg.max_mull, cfg.rollouts, cfg.bottoming_enabled,
            cfg.adaptive_bottom ? r0 : -1);
        ek.commit      = cfg.commit;
        ek.play_digest = play_digest;
        MulliganProfile out = profile;
        out.exhaustive_keep = std::make_shared<const ExhaustiveKeepPolicy>(std::move(ek));
        if (SaveDeckProfile(cfg.out_profile, out))
        { os << "\nexhaustive keep policy written to " << cfg.out_profile << "\n"; }
        else
        { os << "\nWARNING: failed to write " << cfg.out_profile << "\n"; }
    }

    // ---- 6b. Poolable RAW sidecar: per-(size,composition,pd) rollout sum + count, plus a fingerprint
    // gating cross-machine merges (same commit + bucket map + deck; disjoint seed_base). count == R
    // here but is stored per entry so a merge is a plain element-wise sum.
    if (!cfg.out_raw.empty())
    {
        using json = nlohmann::json;
        // Fingerprints: bucket map (sorted member lists) and deck (sorted mainboard names).
        uint64_t bucket_fp = 1469598103934665603ULL;
        for (int b = 0; b < K; ++b)
        { bucket_fp = Fnv("|", bucket_fp); for (const std::string& n : eq.classes[b].members) bucket_fp = Fnv(n + ",", bucket_fp); }
        std::vector<std::string> deck_names;
        for (const Card& c : deck.mainboard) { deck_names.push_back(c.m_name.str()); }
        std::sort(deck_names.begin(), deck_names.end());
        uint64_t deck_fp = 1469598103934665603ULL;
        for (const std::string& n : deck_names) { deck_fp = Fnv(n + ",", deck_fp); }

        json root;
        root["meta"] = {
            { "commit", cfg.commit }, { "play_digest", play_digest },
            { "bucket_fp", bucket_fp }, { "deck_fp", deck_fp },
            { "seed_base", cfg.seed }, { "R", cfg.rollouts }, { "max_mull", cfg.max_mull },
            { "probes", cfg.probes }, { "threshold", cfg.threshold }, { "K", K }, { "equiv_seed", cfg.equiv_seed }
        };
        // Execution-trace Phase B provenance (auto card-scope attribution at re-run): the engine
        // fingerprint (was the compiled engine the same?) and a per-card behaviourally-relevant
        // definition hash (which cards' DATA changed?). A re-run diffs these against the current build
        // + cards.json to derive the changed-card set automatically -- no manual MTG_KEEP_CHANGED_CARDS.
        // Cheap and always written (unknown keys are ignored by older readers).
        root["meta"]["engine_fp"] = std::string(MTG_ENGINE_FP);
        {
            std::set<std::string> distinct_deck;
            for (const Card& c : deck.mainboard) { distinct_deck.insert(c.m_name.str()); }
            json card_defs = json::object();
            for (const std::string& n : distinct_deck)
            { card_defs[n] = CardDatabase::Instance().DefHash(n); }
            root["meta"]["card_defs"] = card_defs;
        }
        json buckets = json::array();
        for (int b = 0; b < K; ++b) { buckets.push_back(eq.classes[b].members); }
        root["buckets"] = buckets;
        json sizes = json::array();
        for (int H = HAND; H >= min_size; --H)
        {
            const SizeTable& t = tables[HAND - H];
            json entries = json::array();
            for (std::size_t i = 0; i < t.comps.size(); ++i)
            {
                json je;
                je["comp"]  = t.comps[i];
                // Actual per-cell rollout sums + counts (adaptive sampling varies count by cell). The
                // merge path reads counts per-entry and rebuilds V=sum/count, so pooling is exact even
                // when two runs sampled a cell to different depths.
                je["sum"]   = { t.sum[i][0], t.sum[i][1] };
                je["sumsq"] = { t.sumsq[i][0], t.sumsq[i][1] };
                je["count"] = { t.cnt[i][0], t.cnt[i][1] };
                // Execution-trace: union over both pd of the card NAMES whose effect ran in this cell's
                // rollouts (names, not indices, so a re-run matches by MTG_KEEP_CHANGED_CARDS regardless
                // of index order). Present only when tracing.
                if (trace_on && i < t.touched.size())
                {
                    std::set<int> u = t.touched[i][0];
                    u.insert(t.touched[i][1].begin(), t.touched[i][1].end());
                    json tn = json::array();
                    for (int idx : u) { tn.push_back(touch_names[idx]); }
                    je["touched"] = tn;
                }
                entries.push_back(je);
            }
            sizes.push_back({ { "H", H }, { "entries", entries } });
        }
        root["sizes"] = sizes;
        if (trace_on) { root["meta"]["traced"] = true; }
        std::ofstream f(cfg.out_raw);
        if (f) { f << root.dump(); os << "raw poolable table written to " << cfg.out_raw << "\n"; }
        else   { os << "WARNING: failed to write " << cfg.out_raw << "\n"; }
    }

    os << "\n--- notable hands (on the play) ---\n";
    decide({ "Unclaimed Territory", "Ancient Ziggurat", "Aether Vial", "Aether Vial",
             "Aether Vial", "Aether Vial", "Predatory Sliver" });          // the 4-Vial trap
    decide({ "Unclaimed Territory", "Ancient Ziggurat", "Aether Vial", "Predatory Sliver",
             "Galerider Sliver", "Striking Sliver", "Sinew Sliver" });      // 2 land + 1 Vial + slivers
    decide({ "Unclaimed Territory", "Cavern of Souls", "Sliver Hive", "Predatory Sliver",
             "Galerider Sliver", "Muscle Sliver", "Striking Sliver" });     // good curve
    os << std::flush;
}

// ---- Offline merge: pool raw sidecars from multiple runs/machines into one policy -----------------
// Each sidecar carries per-(size,composition,pd) rollout sum+count plus a fingerprint {commit,
// bucket_fp, deck_fp, K, max_mull, equiv_seed} and its seed_base(s). Pooling is a plain element-wise
// sum, valid ONLY when every input shares the same play-logic (commit), bucket map and deck, and the
// seed_bases are DISJOINT (else continuations overlap and R is double-counted). We reject any
// mismatch or overlap, sum the compatible ones, rebuild V=sum/count, and run the SAME
// BuildPolicyFromTables used in-run -> an identical serialized policy at the pooled R.
void RunKeepMerge(std::ostream& os, const Decklist& deck, const MulliganProfile& profile,
                  const std::vector<std::string>& raw_paths,
                  const std::string& out_profile, const std::string& out_raw,
                  bool bottoming_enabled)
{
    using json = nlohmann::json;
    if (raw_paths.empty()) { os << "merge: no raw sidecars given (set MTG_MERGE_INPUTS)\n"; return; }

    struct Acc { double sum[2] = { 0, 0 }; double sumsq[2] = { 0, 0 }; long long cnt[2] = { 0, 0 }; };
    std::map<int, std::map<std::vector<int>, Acc>> pooled;   // H -> comp -> summed sum/sumsq/count
    bool have_sumsq = true;   // pooled sumsq is emitted only if EVERY input carried it (else per-cell
                              // variance is incomplete); a direct generation sidecar has it, an older
                              // merged sidecar may not. Enables synthetic R-sweeps / resume from a pool.
    std::vector<std::vector<std::string>> buckets;
    std::string commit;                                     // advisory once play_digest is present
    std::string play_digest;                                // the pooling identity (rollout-config play)
    std::set<std::string> commits;                          // equivalence class of commits pooled together
    uint64_t bucket_fp = 0, deck_fp = 0, equiv_seed = 0;
    int K = -1, max_mull = -1;
    std::set<uint64_t> seed_bases;                           // every base already folded in (overlap guard)
    bool first = true;
    long long files_ok = 0;

    os << "=== KEEP MERGE (" << raw_paths.size() << " sidecar(s)) ===\n";
    for (const std::string& path : raw_paths)
    {
        std::ifstream f(path);
        if (!f) { os << "  SKIP (cannot open): " << path << "\n"; continue; }
        json root;
        try { f >> root; }
        catch (const std::exception& e) { os << "  SKIP (bad json: " << e.what() << "): " << path << "\n"; continue; }
        if (!root.contains("meta") || !root.contains("sizes")) { os << "  SKIP (not a raw sidecar): " << path << "\n"; continue; }
        const json& m = root["meta"];
        const std::string c   = m.value("commit", std::string());
        const std::string pd  = m.value("play_digest", std::string());
        const uint64_t bfp = m.value("bucket_fp", 0ULL);
        const uint64_t dfp = m.value("deck_fp", 0ULL);
        const uint64_t es  = m.value("equiv_seed", 0ULL);
        const int      k   = m.value("K", -1);
        const int      mm  = m.value("max_mull", -1);
        // A file's own bases: an already-merged sidecar lists all its pooled bases; a raw run lists one.
        std::vector<uint64_t> file_bases;
        if (m.contains("pooled_seed_bases")) { file_bases = m["pooled_seed_bases"].get<std::vector<uint64_t>>(); }
        else { file_bases.push_back(m.value("seed_base", 0ULL)); }
        // Collect this file's pooled commits (an already-merged sidecar lists them; a raw run has one).
        std::vector<std::string> file_commits;
        if (m.contains("pooled_commits")) { file_commits = m["pooled_commits"].get<std::vector<std::string>>(); }
        else if (!c.empty()) { file_commits.push_back(c); }

        // Play-logic identity: PREFER the rollout-config play_digest -- a doc-only / other-deck /
        // GUI-only commit bumps `commit` but leaves this deck's play (hence the digest) unchanged, so
        // those sidecars are genuinely poolable. Fall back to the commit hash only when a side predates
        // the digest (legacy sidecar with no play_digest). commit is otherwise advisory.
        auto play_compatible = [&]() -> bool {
            if (!pd.empty() && !play_digest.empty()) { return pd == play_digest; }
            return c == commit;   // legacy fallback: at least one side lacks a play_digest
        };

        if (first)
        {
            commit = c; play_digest = pd; bucket_fp = bfp; deck_fp = dfp; equiv_seed = es; K = k; max_mull = mm;
            buckets = root["buckets"].get<std::vector<std::vector<std::string>>>();
            first = false;
        }
        else if (!play_compatible() || bfp != bucket_fp || dfp != deck_fp || es != equiv_seed
                 || k != K || mm != max_mull)
        {
            os << "  REJECT (fingerprint mismatch): " << path << "\n"
               << "    play_digest " << (pd.empty() ? "<none>" : pd)
               << " vs " << (play_digest.empty() ? "<none>" : play_digest)
               << " | commit "     << c   << " vs " << commit
               << " | bucket_fp "   << bfp << " vs " << bucket_fp
               << " | deck_fp "     << dfp << " vs " << deck_fp
               << " | equiv_seed "  << es  << " vs " << equiv_seed
               << " | K " << k << "/" << K << " | max_mull " << mm << "/" << max_mull << "\n";
            continue;
        }
        bool overlap = false;
        for (uint64_t b : file_bases) { if (seed_bases.count(b)) { overlap = true; break; } }
        if (overlap)
        { os << "  REJECT (seed_base overlap -> would double-count): " << path << "\n"; continue; }
        for (uint64_t b : file_bases) { seed_bases.insert(b); }
        for (const std::string& fc : file_commits) { commits.insert(fc); }   // equivalence class

        for (const json& sz : root["sizes"])
        {
            const int H = sz.value("H", 0);
            for (const json& e : sz["entries"])
            {
                std::vector<int> comp = e["comp"].get<std::vector<int>>();
                Acc& a = pooled[H][comp];
                a.sum[0] += e["sum"][0].get<double>();     a.sum[1] += e["sum"][1].get<double>();
                a.cnt[0] += e["count"][0].get<long long>(); a.cnt[1] += e["count"][1].get<long long>();
                if (e.contains("sumsq"))
                { a.sumsq[0] += e["sumsq"][0].get<double>(); a.sumsq[1] += e["sumsq"][1].get<double>(); }
                else { have_sumsq = false; }
            }
        }
        os << "  + " << path << "  (seed_base " << file_bases.front()
           << (file_bases.size() > 1 ? "+" + std::to_string(file_bases.size() - 1) : "")
           << ", R=" << m.value("R", 0) << ")\n";
        ++files_ok;
    }

    if (files_ok == 0) { os << "merge: no compatible sidecars pooled; nothing written\n"; return; }

    // The deck on the command line must be the one the sidecars were built on (its counts drive the
    // hypergeometric hand weights). Verify the fingerprint; warn loudly on mismatch rather than
    // silently weight with the wrong counts.
    std::vector<std::string> dn;
    for (const Card& c : deck.mainboard) { dn.push_back(c.m_name.str()); }
    std::sort(dn.begin(), dn.end());
    uint64_t my_deck_fp = 1469598103934665603ULL;
    for (const std::string& n : dn) { my_deck_fp = Fnv(n + ",", my_deck_fp); }
    if (my_deck_fp != deck_fp)
    { os << "WARNING: command-line deck fp " << my_deck_fp << " != pooled deck_fp " << deck_fp
         << " -- hand weights may be wrong. Pass the SAME deck the sidecars were built on.\n"; }

    std::map<std::string, int> bucket_of;
    for (int b = 0; b < static_cast<int>(buckets.size()); ++b)
        for (const std::string& nm : buckets[b]) { bucket_of[nm] = b; }
    std::vector<int> count(buckets.size(), 0);
    for (const Card& c : deck.mainboard)
    { auto it = bucket_of.find(c.m_name.str()); if (it != bucket_of.end()) { count[it->second]++; } }

    const int min_size = std::max(1, HAND - max_mull);
    std::vector<SizeTable> tables(HAND - min_size + 1);
    int effective_R = 0;
    for (int H = HAND; H >= min_size; --H)
    {
        SizeTable t;
        auto pit = pooled.find(H);
        if (pit != pooled.end())
        {
            for (const auto& kv : pit->second)
            {
                const int i = static_cast<int>(t.comps.size());
                t.comps.push_back(kv.first);
                t.index[kv.first] = i;
                std::array<double, 2> V = {
                    kv.second.cnt[0] ? kv.second.sum[0] / kv.second.cnt[0] : 0.0,
                    kv.second.cnt[1] ? kv.second.sum[1] / kv.second.cnt[1] : 0.0 };
                t.V.push_back(V);
                t.se.push_back({ 0.0, 0.0 });
                if (H == HAND) { effective_R = std::max<long long>(effective_R, kv.second.cnt[1]); }
            }
        }
        else { os << "WARNING: pooled table missing size " << H << "\n"; }
        tables[HAND - H] = std::move(t);
    }

    os << "pooled " << files_ok << " file(s); " << seed_bases.size()
       << " distinct seed_base(s); effective R=" << effective_R << " per hand (per pd)\n";
    for (int b = 0; b < static_cast<int>(buckets.size()); ++b)
    {
        os << "  [" << b << "] " << buckets[b].front()
           << (buckets[b].size() > 1 ? " (+" + std::to_string(buckets[b].size() - 1) + ")" : "")
           << " x" << count[b] << "\n";
    }

    std::array<std::vector<double>, 2> Dopt;
    ExhaustiveKeepPolicy ek = BuildPolicyFromTables(
        tables, count, buckets, static_cast<int>(deck.mainboard.size()), max_mull, effective_R,
        bottoming_enabled, -1, &Dopt);
    ek.commit = commit;
    os << "merged policy: D_opt(draw)=" << Dopt[0][0] << "  D_opt(play)=" << Dopt[1][0]
       << "  (expected win-turn, optimal keep)\n";

    // ---- Cross-run PRUNE-SET emission (MTG_KEEP_PRUNE_EMIT) --------------------------------------
    // Emit the size-7 cells whose m=0 keep decision is CONFIDENT at this pooled R, so a re-run can skip
    // re-establishing them (see the consume path in RunExhaustiveKeep). A size-7 cell is read ONLY as its
    // own m=0 keep_val and in the Dopt[0] backward induction as min(keep_val(h,0), Dopt[1]) -- it is never
    // a bottoming sub-target (those come from the smaller tables), and Dopt[1..M] come from the smaller
    // tables and are untouched. So confident-mull AND confident-keep size-7 cells are both safe to carry:
    //  * MULL side (V > Dopt[1]): min(V,Dopt[1])==Dopt[1] regardless of V, flag MULL regardless -> freezing
    //    is EXACTLY policy-preserving (Dopt[0] and every flag unchanged).
    //  * KEEP side (V < Dopt[1]): its own flag is KEEP, and it contributes min(V,Dopt[1])==V to Dopt[0]
    //    (the final EV -- NOT a threshold for any decision). Freezing it is DECISION-preserving (all keep
    //    flags correct); only the reported Dopt[0] EV sits at frozen-R precision. No other cell's decision
    //    depends on it. Confident keeps carry the obvious first-hand keeps -- see the user note that this
    //    helps the m=0 decision, not the bottoming sub-tables.
    // Gate = the adaptive STOP gate (shrunk se + erfc flip prob) at a stricter prune_eps, applied to
    // |V - Dopt[1]| so it certifies either side. MTG_KEEP_PRUNE_KEEP=0 emits mulls only (the strictly
    // exactly-lossless subset); default emits both.
    if (const char* pe = std::getenv("MTG_KEEP_PRUNE_EMIT"); pe && *pe)
    {
        if (!have_sumsq)
        {
            os << "PRUNE-EMIT: pooled sidecars lack per-cell sumsq (need it for the freeze gate) -- "
                  "regenerate/merge with sumsq. Nothing written.\n";
        }
        else
        {
            const double prune_eps = []{ const char* s = std::getenv("MTG_KEEP_PRUNE_EPS");
                return (s && *s) ? std::max(0.0, std::atof(s)) : 0.005; }();
            const bool include_keep = []{ const char* s = std::getenv("MTG_KEEP_PRUNE_KEEP");
                return !s || std::string(s) != "0"; }();   // default: carry confident keeps too
            const double se_prior = 8.0;   // matches ExhaustiveKeepConfig::se_prior default (shrink target)
            const double SQRT2    = 1.4142135623730951;
            // Table-7 pooled per-sample variance per pd (the shrink target, guards low-R fake confidence).
            auto& H7pool = pooled[HAND];
            std::array<double, 2> vg7 = { 0.0, 0.0 }; std::array<long long, 2> ng7 = { 0, 0 };
            for (const auto& kv : H7pool)
                for (int pd = 0; pd < 2; ++pd)
                { const long long c = kv.second.cnt[pd];
                  if (c > 1) { const double mn = kv.second.sum[pd] / c;
                               vg7[pd] += std::max(0.0, kv.second.sumsq[pd] / c - mn * mn); ++ng7[pd]; } }
            for (int pd = 0; pd < 2; ++pd) { if (ng7[pd] > 0) { vg7[pd] /= ng7[pd]; } }

            // LOW-PROBABILITY EARLY-CUTOFF (gen-only, play-neutral): a size-7 cell drawn with tiny
            // hypergeometric probability barely moves the P-weighted Dopt thresholds AND rarely occurs
            // in play, so refining it to the full cap is wasted budget. Once such a cell has reached
            // cutoff_R samples (a decent unbiased estimate -- NOT the noisy floor), freeze it at its
            // current keep/mull label even if it is still near-threshold. Draw-P is combinatorial/exact
            // (deck-derived) so this classification never churns across R. OFF (cutoff_P<=0) => the emit
            // is byte-identical to the confident-only set. See grind memory (probability-weighted freeze).
            const double cutoff_P = []{ const char* s = std::getenv("MTG_KEEP_CUTOFF_P");
                return (s && *s) ? std::atof(s) : 0.0; }();
            const long long cutoff_R = []{ const char* s = std::getenv("MTG_KEEP_CUTOFF_R");
                return (s && *s) ? std::atoll(s) : 0; }();
            const bool cutoff_on = (cutoff_P > 0.0 && cutoff_R > 0);
            const long long draw_denom = Comb(static_cast<int>(deck.mainboard.size()), HAND);

            using json = nlohmann::json;
            json frozen = json::array();
            long long n_frozen = 0, n_mull = 0, n_keep = 0, n_size7 = 0, n_cutoff = 0;
            for (const auto& kv : H7pool)
            {
                ++n_size7;
                const std::vector<int>& comp = kv.first;
                const Acc& a = kv.second;
                // Exact draw probability of this bucket composition (multivariate hypergeometric).
                double drawP = 1.0;
                if (cutoff_on)
                {
                    long long num = 1;
                    for (int b = 0; b < K; ++b) { num *= Comb(count[b], comp[b]); }
                    drawP = static_cast<double>(num) / static_cast<double>(draw_denom);
                }
                for (int pd = 0; pd < 2; ++pd)
                {
                    const long long c = a.cnt[pd];
                    if (c < 2) { continue; }                       // no variance -> can't certify
                    const double V   = a.sum[pd] / c;
                    const double thr = Dopt[pd][1];
                    const bool   keep = (V < thr);
                    if (keep && !include_keep) { continue; }       // mulls-only mode
                    const double vc  = std::max(0.0, a.sumsq[pd] / c - V * V);
                    const double vs  = (c * vc + se_prior * vg7[pd]) / (c + se_prior);
                    const double se  = std::sqrt(vs / c);
                    const double flip = (se > 0) ? 0.5 * std::erfc(std::abs(V - thr) / (se * SQRT2))
                                                 : 0.0;            // se==0 => certain (V!=thr)
                    const bool confident = (flip <= prune_eps);
                    const bool cutoff    = cutoff_on && !confident && drawP < cutoff_P && c >= cutoff_R;
                    if (!confident && !cutoff) { continue; }        // near-tie & not low-P -> keep it LIVE
                    json je;
                    je["comp"]  = comp;
                    je["pd"]    = pd;
                    je["keep"]  = keep ? 1 : 0;                    // 1 = KEEP, 0 = MULL (current label)
                    je["sum"]   = a.sum[pd];
                    je["sumsq"] = a.sumsq[pd];
                    je["count"] = c;
                    frozen.push_back(je);
                    ++n_frozen; if (keep) { ++n_keep; } else { ++n_mull; }
                    if (cutoff) { ++n_cutoff; }
                }
            }
            // ---- Phase 2 SUB-TABLE freeze: a size-(7-m) sub-hand confidently ABOVE its keep-bar
            // Dopt[m+1] can never be a KEEP's bottoming argmin (a hand bottoming into it has keep_val >
            // Dopt -> it mulligans), so skipping its rollouts is decision-preserving. Gated by
            // MTG_KEEP_SUB_CUTOFF_R (min samples; 0 => OFF => byte-identical). Reuses the size-7 flip gate
            // per-size (shrink target = that size's pooled per-sample variance) so the confidence margin
            // is the stability guard against a noise-promoted argmin. sizes 6..2 (m=1..5); size-1 (m=6) is
            // forced-keep (no bar) -> skipped.
            const long long sub_cut_R = []{ const char* s = std::getenv("MTG_KEEP_SUB_CUTOFF_R");
                return (s && *s) ? std::atoll(s) : 0; }();
            long long n_subcut = 0;
            if (sub_cut_R > 0)
            {
                for (int H = HAND - 1; H >= 2; --H)
                {
                    auto pit = pooled.find(H);
                    if (pit == pooled.end()) { continue; }
                    const int m = HAND - H;                         // this sub-size is used at mull depth m
                    std::array<double, 2> vgs = { 0.0, 0.0 }; std::array<long long, 2> ngs = { 0, 0 };
                    for (const auto& kv : pit->second)
                        for (int pd = 0; pd < 2; ++pd)
                        { const long long c = kv.second.cnt[pd];
                          if (c > 1) { const double mn = kv.second.sum[pd] / c;
                                       vgs[pd] += std::max(0.0, kv.second.sumsq[pd] / c - mn * mn); ++ngs[pd]; } }
                    for (int pd = 0; pd < 2; ++pd) { if (ngs[pd] > 0) { vgs[pd] /= ngs[pd]; } }
                    for (const auto& kv : pit->second)
                    {
                        const Acc& a = kv.second;
                        for (int pd = 0; pd < 2; ++pd)
                        {
                            const long long c = a.cnt[pd];
                            if (c < 2 || c < sub_cut_R) { continue; }
                            const double V   = a.sum[pd] / c;
                            const double thr = Dopt[pd][m + 1];      // keep-bar for a size-(7-m) sub-hand
                            if (V <= thr) { continue; }              // only freeze cells ABOVE the bar
                            const double vc = std::max(0.0, a.sumsq[pd] / c - V * V);
                            const double vs = (c * vc + se_prior * vgs[pd]) / (c + se_prior);
                            const double se = std::sqrt(vs / c);
                            const double flip = (se > 0) ? 0.5 * std::erfc(std::abs(V - thr) / (se * SQRT2))
                                                         : 0.0;
                            if (flip > prune_eps) { continue; }      // too close to the bar -> keep it LIVE
                            json je;
                            je["comp"]  = kv.first;
                            je["pd"]    = pd;
                            je["size"]  = H;
                            je["keep"]  = 0;                         // sub-cells carry no keep decision
                            je["sum"]   = a.sum[pd];
                            je["sumsq"] = a.sumsq[pd];
                            je["count"] = c;
                            frozen.push_back(je);
                            ++n_subcut; ++n_frozen;
                        }
                    }
                }
            }
            json root;
            root["meta"] = {
                { "kind", include_keep ? "confident_size7" : "confident_mull_size7" },
                { "commit", commit }, { "play_digest", play_digest },
                { "bucket_fp", bucket_fp }, { "deck_fp", deck_fp }, { "equiv_seed", equiv_seed },
                { "K", K }, { "max_mull", max_mull }, { "source_R", effective_R },
                { "prune_eps", prune_eps }, { "frozen_cell_sides", n_frozen },
                { "frozen_mull", n_mull }, { "frozen_keep", n_keep }, { "size7_cells", n_size7 },
                { "frozen_subcut", n_subcut }
            };
            root["frozen"] = frozen;
            std::ofstream f(pe);
            if (f)
            {
                f << root.dump();
                os << "PRUNE-EMIT: " << n_frozen << " frozen cell-sides (" << n_mull << " mull, "
                   << n_keep << " keep size-7; " << n_subcut << " sub-table; of " << (2 * n_size7)
                   << " size-7) at prune_eps=" << prune_eps << ", source_R=" << effective_R
                   << " -> " << pe << "\n";
            }
            else { os << "PRUNE-EMIT: WARNING failed to write " << pe << "\n"; }
        }
    }

    if (!out_profile.empty())
    {
        MulliganProfile out = profile;
        out.exhaustive_keep = std::make_shared<const ExhaustiveKeepPolicy>(ek);
        if (SaveDeckProfile(out_profile, out)) { os << "merged keep policy -> " << out_profile << "\n"; }
        else { os << "WARNING: failed to write " << out_profile << "\n"; }
    }

    // Re-emit the pooled table as a sidecar so merges chain (merge of merges). It lists ALL folded-in
    // seed_bases so a downstream merge still detects any overlap.
    if (!out_raw.empty())
    {
        std::vector<uint64_t> bases(seed_bases.begin(), seed_bases.end());
        std::vector<std::string> commit_list(commits.begin(), commits.end());
        json root;
        root["meta"] = {
            { "commit", commit }, { "play_digest", play_digest },
            { "pooled_commits", commit_list },   // the equivalence class of commits pooled here
            { "bucket_fp", bucket_fp }, { "deck_fp", deck_fp },
            { "seed_base", bases.empty() ? 0ULL : bases.front() },
            { "pooled_seed_bases", bases }, { "pooled_files", files_ok },
            { "R", effective_R }, { "max_mull", max_mull }, { "K", K }, { "equiv_seed", equiv_seed }
        };
        json jb = json::array();
        for (const auto& mem : buckets) { jb.push_back(mem); }
        root["buckets"] = jb;
        json sizes = json::array();
        for (int H = HAND; H >= min_size; --H)
        {
            const SizeTable& t = tables[HAND - H];
            json entries = json::array();
            for (std::size_t i = 0; i < t.comps.size(); ++i)
            {
                const Acc& a = pooled[H][t.comps[i]];
                json je;
                je["comp"]  = t.comps[i];
                je["sum"]   = { a.sum[0], a.sum[1] };
                je["count"] = { a.cnt[0], a.cnt[1] };
                if (have_sumsq) { je["sumsq"] = { a.sumsq[0], a.sumsq[1] }; }
                entries.push_back(je);
            }
            sizes.push_back({ { "H", H }, { "entries", entries } });
        }
        root["sizes"] = sizes;
        std::ofstream f(out_raw);
        if (f) { f << root.dump(); os << "merged raw table -> " << out_raw << "\n"; }
        else   { os << "WARNING: failed to write " << out_raw << "\n"; }
    }
    os << std::flush;
}
